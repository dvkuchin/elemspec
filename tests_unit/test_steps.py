from __future__ import annotations

import unittest

from elemspec.steps import контракт_языка, разобрать


class ПлатформенныйЛокаторTest(unittest.TestCase):
    def test_разбирает_ожидание_формы(self) -> None:
        self.assertEqual(
            ("проверить_заголовок_формы", {"заголовок_формы": "Clients"}),
            разобрать('открылась форма "Clients"'),
        )

    def test_разбирает_ожидание_диалога(self) -> None:
        self.assertEqual(
            ("проверить_заголовок_диалога", {"заголовок_диалога": "Delete client"}),
            разобрать('открылся диалог "Delete client"'),
        )

    def test_разбирает_клик_по_пункту_навигации(self) -> None:
        self.assertEqual(
            ("клик", {"пункт_навигации": "Sales"}),
            разобрать('я нажимаю пункт навигации "Sales"'),
        )

    def test_разбирает_клик_по_платформенной_команде(self) -> None:
        self.assertEqual(
            ("клик", {"команда": "Готово"}),
            разобрать('я нажимаю команду "Готово"'),
        )

    def test_разбирает_команду_в_модальном_диалоге(self) -> None:
        self.assertEqual(
            ("клик", {"команда_диалога": "Delete"}),
            разобрать('я нажимаю команду "Delete" в диалоге'),
        )

    def test_разбирает_проверку_видимости_команды(self) -> None:
        self.assertEqual(
            ("проверить_элемент", {"команда": "Готово", "видимый": True}),
            разобрать('видна команда "Готово"'),
        )

    def test_разбирает_hover_пункта_навигации(self) -> None:
        self.assertEqual(
            ("навести_указатель", {"пункт_навигации": "Sales"}),
            разобрать('я навожу указатель на пункт навигации "Sales"'),
        )

    def test_разбирает_ввод_в_поле_именованного_компонента(self) -> None:
        self.assertEqual(
            (
                "ввести",
                {
                    "значение": "SAMPLE_USER",
                    "поле_компонента": "login-edit",
                },
            ),
            разобрать('я ввожу "SAMPLE_USER" в поле "login-edit"'),
        )

    def test_публикует_локатор_в_контракте_dsl(self) -> None:
        фразы = [запись["фраза"] for запись in контракт_языка()]
        self.assertTrue(any("пункт навигации" in фраза for фраза in фразы))
        self.assertTrue(any("поле" in фраза for фраза in фразы))

    def test_разбирает_проверку_значения_поля(self) -> None:
        self.assertEqual(
            (
                "проверить_значение_поля",
                {"поле_компонента": "Имя", "ожидаемое": "Иван"},
            ),
            разобрать('поле "Имя" имеет значение "Иван"'),
        )

    def test_разбирает_проверку_пустого_поля(self) -> None:
        self.assertEqual(
            (
                "проверить_значение_поля",
                {"поле_компонента": "Имя", "ожидаемое": ""},
            ),
            разобрать('поле "Имя" пусто'),
        )

    def test_разбирает_очистку_поля(self) -> None:
        self.assertEqual(
            ("очистить_поле", {"поле_компонента": "Имя"}),
            разобрать('я очищаю поле "Имя"'),
        )

    def test_разбирает_выбор_значения_поля(self) -> None:
        self.assertEqual(
            (
                "выбрать_значение_поля",
                {"значение": "Москва", "поле_компонента": "БизнесРегион"},
            ),
            разобрать('я выбираю "Москва" в поле "БизнесРегион"'),
        )

    def test_разбирает_выбор_любого_значения_поля(self) -> None:
        self.assertEqual(
            (
                "выбрать_любое_значение_поля",
                {"значение": "Москва", "поле_компонента": "БизнесРегион"},
            ),
            разобрать(
                'я выбираю любое значение "Москва" в поле "БизнесРегион"'
            ),
        )

    def test_разбирает_наличие_строки_таблицы(self) -> None:
        self.assertEqual(
            (
                "проверить_строки_таблицы",
                {
                    "таблица": "ОсновнаяТаблица",
                    "колонка": "Наименование",
                    "значение_ячейки": "Иван",
                },
            ),
            разобрать(
                'в таблице "ОсновнаяТаблица" есть строка, где колонка '
                '"Наименование" имеет значение "Иван"'
            ),
        )

    def test_разбирает_отсутствие_строки_таблицы(self) -> None:
        действие, аргументы = разобрать(
            'в таблице "ОсновнаяТаблица" нет строки, где колонка '
            '"Наименование" имеет значение "Иван"'
        )
        self.assertEqual("проверить_строки_таблицы", действие)
        self.assertEqual(0, аргументы["количество"])

    def test_разбирает_открытие_строки_таблицы(self) -> None:
        self.assertEqual(
            (
                "открыть_строку_таблицы",
                {
                    "таблица": "ОсновнаяТаблица",
                    "колонка": "Наименование",
                    "значение_ячейки": "Иван",
                },
            ),
            разобрать(
                'я открываю строку в таблице "ОсновнаяТаблица", где колонка '
                '"Наименование" имеет значение "Иван"'
            ),
        )


if __name__ == "__main__":
    unittest.main()
