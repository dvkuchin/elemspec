СОСТОЯНИЕ_ПОДТВЕРЖДЕНО = "VERIFIED"
СОСТОЯНИЕ_ДЕФЕКТ_НАЙДЕН = "BUG_FOUND"
СОСТОЯНИЕ_НЕ_ПОДТВЕРЖДЕНО = "UNVERIFIED"


def открыть_разведку(каталог: Path) -> dict[str, Any]:
    разведка = {
        "id": str(uuid.uuid4()),
        "события": [],
    }
    _сохранить(каталог, разведка)
    return {"разведка": разведка["id"]}


def записать_событие(
    каталог: Path,
    id_разведки: str,
    операция: str,
    запрос: dict[str, Any],
    результат: dict[str, Any],
) -> None:
    разведка = загрузить_разведку(каталог, id_разведки)
    сохранённый_результат = результат
    if операция == "snapshot":
        сохранённый_результат = {
            "url": результат.get("url"),
            "заголовок": результат.get("заголовок"),
            "элементов": len(результат.get("элементы") or []),
            "обрезан": bool(результат.get("обрезан")),
        }
    разведка["события"].append(
        {
            "номер": len(разведка["события"]) + 1,
            "операция": операция,
            "запрос": {
                ключ: (
                    "***"
                    if операция == "fill" and ключ == "значение"
                    else значение
                )
                for ключ, значение in запрос.items()
                if ключ not in {"id", "операция"}
            },
            "результат": сохранённый_результат,
        }
    )
    _сохранить(каталог, разведка)


def загрузить_разведку(каталог: Path, id_разведки: str) -> dict[str, Any]:
    файл = _файл(каталог, id_разведки)
    try:
        данные = json.loads(файл.read_text(encoding="utf-8"))
    except FileNotFoundError as ошибка:
        raise ОшибкаАгентскогоAPI("browser evidence не найден") from ошибка
    except (OSError, json.JSONDecodeError) as ошибка:
        raise ОшибкаАгентскогоAPI(
            f"не удалось прочитать browser evidence: {ошибка}"
        ) from ошибка
    if данные.get("id") != str(uuid.UUID(id_разведки)):
        raise ОшибкаАгентскогоAPI("browser evidence повреждён")
    return данные


def проверить_доказательства(
    проверка_черновика: dict[str, Any],
    разведка: dict[str, Any],
) -> dict[str, Any]:
    """Сопоставить адресуемые шаги черновика с фактами browser-сессии."""
    события = разведка.get("события") or []
    открытия = [
        {**событие, "_номер_evidence": событие.get("номер", 0)}
        for событие in события
        if событие.get("операция") == "start"
    ]

    def результаты(*операции: str) -> list[dict[str, Any]]:
        return [
            {
                **(событие.get("результат") or {}),
                "_номер_evidence": событие.get("номер", 0),
            }
            for событие in события
            if событие.get("операция") in операции
        ]

    проверки = результаты("locator-check", "locator-pick")
    проверки_строк = результаты("table-row-check")
    открытия_строк = результаты("table-row-open")
    клики = результаты("click")
    наведения = результаты("hover")
    вводы = результаты("fill")
    выборы = результаты("select-value")
    любые_выборы = результаты("select-any-value")
    значения = результаты("read-value")
    снимки = результаты("snapshot")
    клавиши = результаты("key")

    подтверждённые = []
    расхождения = []
    неподтверждённые = []
    for сценарий in проверка_черновика.get("сценарии", []):
        номер_evidence = 0
        for шаг in сценарий.get("шаги", []):
            действие = шаг["действие"]
            факт: dict[str, Any] | None = None
            if действие == "открыть":
                факт = _найти_открытие(
                    _после(открытия, номер_evidence), шаг["аргументы"]
                )
            elif действие in {
                "ждать_элемент",
                "проверить_элемент",
                "проверить_текст",
                "проверить_заголовок_формы",
                "проверить_заголовок_диалога",
            }:
                факт = _найти_проверку(
                    _после(проверки, номер_evidence),
                    шаг["аргументы"],
                    действие,
                )
            elif действие in {"клик", "клик_открывает_вкладку"}:
                факт = _найти_клик(
                    _после(клики, номер_evidence), шаг["аргументы"]
                )
            elif действие == "навести_указатель":
                факт = _найти_клик(
                    _после(наведения, номер_evidence), шаг["аргументы"]
                )
            elif действие in {"ввести", "очистить_поле"}:
                факт = _найти_клик(
                    _после(вводы, номер_evidence), шаг["аргументы"]
                )
            elif действие == "выбрать_значение_поля":
                факт = _найти_выбор(
                    _после(выборы, номер_evidence), шаг["аргументы"]
                )
            elif действие == "выбрать_любое_значение_поля":
                факт = _найти_выбор(
                    _после(любые_выборы, номер_evidence), шаг["аргументы"]
                )
            elif действие == "проверить_значение_поля":
                факт = _найти_значение(
                    _после(значения, номер_evidence), шаг["аргументы"]
                )
            elif действие == "проверить_строки_таблицы":
                факт = _найти_строки_таблицы(
                    _после(проверки_строк, номер_evidence),
                    шаг["аргументы"],
                    действие,
                )
            elif действие == "открыть_строку_таблицы":
                факт = _найти_строки_таблицы(
                    _после(открытия_строк, номер_evidence),
                    шаг["аргументы"],
                    действие,
                )
            elif действие == "нажать_клавишу":
                факт = next(
                    (
                        результат
                        for результат in _после(клавиши, номер_evidence)
                        if результат.get("клавиша")
                        == шаг["аргументы"].get("клавиша")
                    ),
                    None,
                )
            elif действие in {"проверить_заголовок", "проверить_адрес"}:
                доступные_снимки = _после(снимки, номер_evidence)
                доступные_открытия = _после(открытия, номер_evidence)
                факт = доступные_снимки[0] if доступные_снимки else (
                    {
                        **(доступные_открытия[0].get("результат") or {}),
                        "_номер_evidence": доступные_открытия[0].get(
                            "_номер_evidence", 0
                        ),
                    }
                    if доступные_открытия else None
                )
            else:
                continue

            описание = {
                "сценарий": сценарий["имя"],
                "номер_шага": шаг["номер"],
                "фраза": шаг["фраза"],
                "действие": действие,
            }
            if факт is None:
                неподтверждённые.append(
                    {
                        **описание,
                        "причина": "нет соответствующего browser evidence",
                    }
                )
                continue

            номер_evidence = int(факт.get("_номер_evidence", номер_evidence))

            совпало, ожидаемое, фактическое = _сопоставить(шаг, факт)
            запись = {
                **описание,
                "ожидалось": ожидаемое,
                "фактически": фактическое,
            }
            if совпало:
                подтверждённые.append(запись)
            else:
                расхождения.append(запись)

    if неподтверждённые:
        состояние = СОСТОЯНИЕ_НЕ_ПОДТВЕРЖДЕНО
    elif расхождения:
        состояние = СОСТОЯНИЕ_ДЕФЕКТ_НАЙДЕН
    else:
        состояние = СОСТОЯНИЕ_ПОДТВЕРЖДЕНО
    return {
        "разведка": разведка["id"],
        "состояние": состояние,
        "подтверждённые": подтверждённые,
        "расхождения": расхождения,
        "неподтверждённые": неподтверждённые,
    }


def _после(
    кандидаты: list[dict[str, Any]], номер_evidence: int
) -> list[dict[str, Any]]:
    return [
        кандидат
        for кандидат in кандидаты
        if int(кандидат.get("_номер_evidence", 0)) > номер_evidence
    ]


def _найти_проверку(
    проверки: list[dict[str, Any]],
    аргументы: dict[str, Any],
    действие: str,
) -> dict[str, Any] | None:
    вид, значение = _локатор_из_аргументов(аргументы)
    совпадающие = []
    for результат in проверки:
        кандидат = результат.get("локатор", результат)
        if кандидат.get("вид") == вид and кандидат.get("значение") == значение:
            if "доказательство" in результат:
                for проверка in (
                    результат["доказательство"].get("кандидаты", [])
                ):
                    if (
                        проверка.get("вид") == вид
                        and проверка.get("значение") == значение
                    ):
                        кандидат = {
                            **проверка,
                            "_номер_evidence": результат.get(
                                "_номер_evidence", 0
                            ),
                        }
                        совпадающие.append(кандидат)
            else:
                совпадающие.append(результат)
    for результат in совпадающие:
        if _проверка_элемента_совпала(результат, аргументы, действие):
            return результат
    return совпадающие[0] if совпадающие else None


def _проверка_элемента_совпала(
    результат: dict[str, Any],
    аргументы: dict[str, Any],
    действие: str,
) -> bool:
    if действие in {
        "проверить_заголовок_формы",
        "проверить_заголовок_диалога",
    }:
        return int(результат.get("видимых", 0)) == 1
    if действие == "проверить_текст":
        видимые = int(результат.get("видимых", 0))
        return (видимые == 0) if аргументы.get("отсутствует") else (видимые > 0)
    фактическое = (
        int(результат.get("видимых", 0))
        if аргументы.get("видимый")
        else int(результат.get("совпадений", 0))
    )
    ожидаемое = аргументы.get("количество")
    return фактическое > 0 if ожидаемое is None else фактическое == int(ожидаемое)


def _найти_открытие(
    открытия: list[dict[str, Any]],
    аргументы: dict[str, Any],
) -> dict[str, Any] | None:
    """Найти навигацию по запрошенному URL, не подменяя его конечным redirect URL."""
    ожидаемый = str(аргументы.get("адрес", ""))
    if not открытия:
        return None
    if ожидаемый.startswith("/"):
        return открытия[0]
    нормализованный = ожидаемый.rstrip("/")
    for событие in открытия:
        запрошенный = str((событие.get("запрос") or {}).get("url", ""))
        if запрошенный.rstrip("/") == нормализованный:
            return событие
    return открытия[0]


def _найти_клик(
    клики: list[dict[str, Any]],
    аргументы: dict[str, Any],
) -> dict[str, Any] | None:
    вид, значение = _локатор_из_аргументов(аргументы)
    for результат in клики:
        локатор = результат.get("локатор") or {}
        if локатор.get("вид") == вид and локатор.get("значение") == значение:
            return результат
    return None


def _найти_значение(
    значения: list[dict[str, Any]],
    аргументы: dict[str, Any],
) -> dict[str, Any] | None:
    вид, значение_локатора = _локатор_из_аргументов(аргументы)
    ожидаемое = str(аргументы.get("ожидаемое", ""))
    совпадающий_локатор = []
    for результат in значения:
        локатор = результат.get("локатор") or {}
        if (
            локатор.get("вид") == вид
            and локатор.get("значение") == значение_локатора
        ):
            совпадающий_локатор.append(результат)
            if str(результат.get("значение", "")) == ожидаемое:
                return результат
    return совпадающий_локатор[0] if совпадающий_локатор else None


def _найти_выбор(
    выборы: list[dict[str, Any]],
    аргументы: dict[str, Any],
) -> dict[str, Any] | None:
    вид, значение_локатора = _локатор_из_аргументов(аргументы)
    ожидаемое = str(аргументы.get("значение", ""))
    совпадающий_локатор = []
    for результат in выборы:
        локатор = результат.get("локатор") or {}
        if (
            локатор.get("вид") == вид
            and локатор.get("значение") == значение_локатора
        ):
            совпадающий_локатор.append(результат)
            if str(результат.get("значение", "")) == ожидаемое:
                return результат
    return совпадающий_локатор[0] if совпадающий_локатор else None


def _найти_строки_таблицы(
    проверки: list[dict[str, Any]],
    аргументы: dict[str, Any],
    действие: str,
) -> dict[str, Any] | None:
    совпадающие = []
    for результат in проверки:
        if (
            результат.get("таблица") == аргументы.get("таблица")
            and результат.get("колонка") == аргументы.get("колонка")
            and результат.get("значение") == аргументы.get("значение_ячейки")
        ):
            совпадающие.append(результат)
    for результат in совпадающие:
        количество = int(результат.get("совпадений", 0))
        if действие == "открыть_строку_таблицы" and количество == 1:
            return результат
        ожидаемое = аргументы.get("количество")
        if действие == "проверить_строки_таблицы" and (
            (ожидаемое is None and количество > 0)
            or (ожидаемое is not None and количество == int(ожидаемое))
        ):
            return результат
    return совпадающие[0] if совпадающие else None


def _локатор_из_аргументов(аргументы: dict[str, Any]) -> tuple[str, str]:
    for поле, вид in (
        ("заголовок_формы", "заголовок формы"),
        ("заголовок_диалога", "заголовок диалога"),
        ("поле_компонента", "поле"),
        ("команда_диалога", "команда диалога"),
        ("команда", "команда"),
        ("пункт_навигации", "пункт навигации"),
        ("тест_ид", "элемент"),
        ("текст", "текст"),
        ("селектор", "селектор"),
    ):
        if поле in аргументы:
            return вид, str(аргументы[поле])
    return "", ""


def _сопоставить(
    шаг: dict[str, Any],
    факт: dict[str, Any],
) -> tuple[bool, Any, Any]:
    действие = шаг["действие"]
    аргументы = шаг["аргументы"]
    if действие == "открыть":
        ожидалось = аргументы.get("адрес")
        результат = факт.get("результат") or {}
        запрошенный = (
            (факт.get("запрос") or {}).get("url")
            or результат.get("запрошенный_url")
        )
        конечный = результат.get("url")
        фактически = {
            "запрошен": запрошенный,
            "конечный": конечный,
            "перенаправлен": bool(результат.get("перенаправлен"))
            or str(запрошенный).rstrip("/") != str(конечный).rstrip("/"),
            "цепочка": результат.get("цепочка_url")
            or [url for url in (запрошенный, конечный) if url],
        }
        # Шаг открытия доказывает сам запрос и успешную разрешённую навигацию.
        # Конечный URL после redirect проверяется отдельным шагом "адрес содержит".
        совпало = bool(конечный) if str(ожидалось).startswith("/") else (
            str(ожидалось).rstrip("/") == str(запрошенный).rstrip("/")
            and bool(конечный)
        )
        return совпало, ожидалось, фактически
    if действие in {"ждать_элемент", "проверить_элемент"}:
        видимые = int(факт.get("видимых", 0))
        совпадений = int(факт.get("совпадений", 0))
        if действие == "ждать_элемент":
            return совпадений > 0, "> 0", совпадений
        ожидаемое = аргументы.get("количество")
        фактическое = видимые if аргументы.get("видимый") else совпадений
        if ожидаемое is None:
            совпало = фактическое > 0
            ожидаемое = "> 0"
        else:
            совпало = фактическое == int(ожидаемое)
        return совпало, ожидаемое, фактическое
    if действие in {
        "проверить_заголовок_формы",
        "проверить_заголовок_диалога",
    }:
        ожидалось = str(
            аргументы.get("заголовок_формы")
            or аргументы.get("заголовок_диалога")
            or ""
        )
        фактическое = {
            "видимых": int(факт.get("видимых", 0)),
            "тексты": факт.get("тексты") or [],
        }
        return фактическое["видимых"] == 1, ожидалось, фактическое
    if действие == "проверить_текст":
        видимые = int(факт.get("видимых", 0))
        отсутствует = bool(аргументы.get("отсутствует"))
        return (
            (видимые == 0) if отсутствует else (видимые > 0),
            "текст отсутствует" if отсутствует else "текст виден",
            {"видимых": видимые},
        )
    if действие == "проверить_заголовок":
        ожидалось = str(аргументы.get("текст"))
        фактически = str(факт.get("заголовок", ""))
        return ожидалось in фактически, ожидалось, фактически
    if действие == "проверить_адрес":
        ожидалось = str(аргументы.get("адрес"))
        фактически = str(факт.get("url", ""))
        return ожидалось in фактически, ожидалось, фактически
    if действие == "клик_открывает_вкладку":
        ожидалось = str(аргументы.get("адрес"))
        новые = факт.get("новые_страницы") or []
        совпало = any(ожидалось in str(url) for url in новые)
        return совпало, ожидалось, новые
    if действие == "навести_указатель":
        return True, "указатель наведён", _без_служебных_полей(факт)
    if действие == "очистить_поле":
        фактически = int(факт.get("введено_символов", -1))
        return фактически == 0, 0, фактически
    if действие in {"выбрать_значение_поля", "выбрать_любое_значение_поля"}:
        ожидалось = str(аргументы.get("значение", ""))
        фактически = str(факт.get("фактическое_значение", ""))
        return фактически == ожидалось, ожидалось, фактически
    if действие == "проверить_значение_поля":
        ожидалось = str(аргументы.get("ожидаемое", ""))
        фактически = str(факт.get("значение", ""))
        return фактически == ожидалось, ожидалось, фактически
    if действие == "проверить_строки_таблицы":
        фактически = int(факт.get("совпадений", 0))
        ожидалось = аргументы.get("количество")
        if ожидалось is None:
            return фактически > 0, "> 0", фактически
        return фактически == int(ожидалось), int(ожидалось), фактически
    if действие == "открыть_строку_таблицы":
        фактически = int(факт.get("совпадений", 0))
        return фактически == 1, 1, фактически
    return True, "клик выполнен", _без_служебных_полей(факт)


def _без_служебных_полей(факт: dict[str, Any]) -> dict[str, Any]:
    return {
        ключ: значение
        for ключ, значение in факт.items()
        if not ключ.startswith("_")
    }


def _файл(каталог: Path, id_разведки: str) -> Path:
    try:
        нормализованный = str(uuid.UUID(id_разведки))
    except (ValueError, AttributeError) as ошибка:
        raise ОшибкаАгентскогоAPI(
            "некорректный идентификатор browser evidence"
        ) from ошибка
    return каталог.resolve() / f"{нормализованный}.json"


def _сохранить(каталог: Path, разведка: dict[str, Any]) -> None:
    каталог.mkdir(parents=True, exist_ok=True)
    файл = _файл(каталог, разведка["id"])
    дескриптор, путь = tempfile.mkstemp(
        prefix=".discovery.",
        dir=каталог,
        text=True,
    )
    временный = Path(путь)
    try:
        with os.fdopen(дескриптор, "w", encoding="utf-8") as поток:
            json.dump(разведка, поток, ensure_ascii=False, indent=2)
        os.replace(временный, файл)
    except OSError as ошибка:
        временный.unlink(missing_ok=True)
        raise ОшибкаАгентскогоAPI(
            f"не удалось сохранить browser evidence: {ошибка}"
        ) from ошибка
