    def _локатор_ref(self, ref: str) -> dict[str, str]:
        if ref in self._выбранные_локаторы:
            return self._выбранные_локаторы[ref]
        описание = self._описания_ссылок.get(ref) or {}
        if (
            описание.get("компонент") == КОМПОНЕНТ_ПУНКТА_НАВИГАЦИИ
            and описание.get("метка")
        ):
            return {
                "вид": "пункт навигации",
                "значение": описание["метка"],
            }
        if (
            описание.get("компонент") == КОМПОНЕНТ_КОМАНДЫ
            and описание.get("метка")
        ):
            if self._получить_ref(ref).locator(
                'xpath=ancestor::*[@role="alertdialog"][1]'
            ).count() == 1:
                return {
                    "вид": "команда диалога",
                    "значение": описание["метка"],
                }
            return {"вид": "команда", "значение": описание["метка"]}
        if описание.get("компонент_поля"):
            return {
                "вид": "поле",
                "значение": описание["компонент_поля"],
            }
        if (
            описание.get("testid") == ТЕСТ_ИД_ЗАГОЛОВКА_ФОРМЫ
            and описание.get("текст")
        ):
            return {"вид": "заголовок формы", "значение": описание["текст"]}
        if (
            self._это_заголовок_диалога(self._получить_ref(ref), описание)
            and описание.get("текст")
        ):
            return {"вид": "заголовок диалога", "значение": описание["текст"]}
        if описание.get("testid"):
            return {"вид": "элемент", "значение": описание["testid"]}
        if описание.get("текст"):
            return {"вид": "текст", "значение": описание["текст"]}
        raise ОшибкаАгентскогоAPI(
            f"для '{ref}' сначала вызовите locator-pick"
        )

    @staticmethod
    def _это_заголовок_диалога(элемент, описание: dict[str, Any]) -> bool:
        внутри_диалога = элемент.locator(
            'xpath=ancestor::*[@role="alertdialog"][1]'
        ).count() == 1
        тег = str(описание.get("тег") or "")
        testid = str(описание.get("testid") or "")
        компонент = описание.get("компонент")
        return внутри_диалога and (
            тег in {"h1", "h2", "h3", "h4", "h5", "h6"}
            or компонент == "title"
            or testid.endswith("title")
            or "title-" in testid
        )

    @staticmethod
    def _компонент_поля(элемент, тег: str) -> str | None:
        тип = (элемент.get_attribute("type") or "text").lower()
        редактируемые_типы = {
            "text", "password", "email", "search", "tel", "url", "number"
        }
        редактируем = (
            тег == "textarea"
            or (тег == "input" and тип in редактируемые_типы)
            or элемент.get_attribute("contenteditable") == "true"
        )
        if not редактируем:
            return None
        контейнер = элемент.locator("xpath=ancestor::*[@data-testid][1]")
        if контейнер.count() != 1:
            return None
        return контейнер.get_attribute("data-testid")

    @staticmethod
    def _компонент_таблицы(элемент) -> str | None:
        if элемент.get_attribute("data-component") == КОМПОНЕНТ_ТАБЛИЦЫ:
            таблица = элемент
        else:
            таблица = элемент.locator(
                f'xpath=ancestor::*[@data-component="{КОМПОНЕНТ_ТАБЛИЦЫ}"][1]'
            )
            if таблица.count() != 1:
                return None
        контейнер = таблица.locator("xpath=ancestor::*[@data-testid][1]")
        if контейнер.count() != 1:
            return None
        return контейнер.get_attribute("data-testid")

    @staticmethod
    def _колонка_таблицы(элемент) -> str | None:
        testid = элемент.get_attribute("data-testid")
        if not testid:
            return None
        ячейка = элемент.locator(
            'xpath=ancestor::*[@data-component="table-cell"][1]'
        )
        return testid if ячейка.count() == 1 else None
