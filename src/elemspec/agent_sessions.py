"""Персистентные рабочие сессии создания и изменения одного теста."""

from __future__ import annotations

import difflib
import hashlib
import json
import os
import tempfile
import uuid
from pathlib import Path
from typing import Any

from .agent import ОшибкаАгентскогоAPI, _проверить_имя, проверить_черновик
from .agent_evidence import (
    СОСТОЯНИЕ_ДЕФЕКТ_НАЙДЕН,
    СОСТОЯНИЕ_НЕ_ПОДТВЕРЖДЕНО,
    загрузить_разведку,
    проверить_доказательства,
)
from .project import ПолитикаХостов


СОСТОЯНИЕ_ОТКРЫТА = "OPEN"
СОСТОЯНИЕ_ЖДЁТ_ПОДТВЕРЖДЕНИЯ = "AWAITING_CONFIRMATION"
СОСТОЯНИЕ_ЖДЁТ_ПОДТВЕРЖДЕНИЯ_ДЕФЕКТА = "AWAITING_BUG_CONFIRMATION"
СОСТОЯНИЕ_ПРИМЕНЕНА = "APPLIED"


def открыть_сессию(
    каталог_тестов: Path,
    каталог_сессий: Path,
    имя: str,
) -> dict[str, Any]:
    """Открыть сессию создания или изменения, автоматически определив режим."""
    имя = _проверить_имя(имя)
    каталог_тестов = каталог_тестов.resolve()
    цель = каталог_тестов / имя
    существует = цель.exists()
    if существует and (
        not цель.is_dir()
        or not (цель / "init.json").is_file()
        or not (цель / "test.feature").is_file()
    ):
        raise ОшибкаАгентскогоAPI(
            f"'{имя}' уже существует, но не является полным тестом"
        )
    if существует and (
        (цель / "init.json").is_symlink()
        or (цель / "test.feature").is_symlink()
    ):
        raise ОшибкаАгентскогоAPI("файлы теста не могут быть символическими ссылками")

    исходник = _прочитать_пару(цель) if существует else None
    сессия = {
        "id": str(uuid.uuid4()),
        "тест": имя,
        "режим": "update" if существует else "create",
        "состояние": СОСТОЯНИЕ_ОТКРЫТА,
        "базовая_ревизия": _ревизия(исходник),
        "черновик": None,
        "ревизия_черновика": None,
        "diff": None,
        "browser_evidence": None,
        "подтверждённый_дефект": None,
    }
    _сохранить_сессию(каталог_сессий, сессия)
    return _публичная_сессия(сессия)


def подготовить(
    каталог_тестов: Path,
    каталог_сессий: Path,
    id_сессии: str,
    init_json: str,
    feature: str,
    политика: ПолитикаХостов | None = None,
    каталог_разведок: Path | None = None,
    id_разведки: str | None = None,
) -> dict[str, Any]:
    """Проверить черновик/evidence и подготовить безопасное применение."""
    сессия = _загрузить_сессию(каталог_сессий, id_сессии)
    if сессия["состояние"] == СОСТОЯНИЕ_ПРИМЕНЕНА:
        raise ОшибкаАгентскогоAPI("сессия уже применена")

    проверка = проверить_черновик(
        сессия["тест"],
        init_json,
        feature,
        политика,
    )
    if not проверка["исполняем"]:
        return {
            **_публичная_сессия(сессия),
            "проверка": проверка,
            "применено": False,
        }

    browser_evidence = None
    if каталог_разведок is not None or id_разведки is not None:
        if каталог_разведок is None or id_разведки is None:
            raise ОшибкаАгентскогоAPI(
                "для проверки evidence нужны каталог и идентификатор разведки"
            )
        browser_evidence = проверить_доказательства(
            проверка,
            загрузить_разведку(каталог_разведок, id_разведки),
        )
        if browser_evidence["состояние"] == СОСТОЯНИЕ_НЕ_ПОДТВЕРЖДЕНО:
            return {
                **_публичная_сессия(сессия),
                "состояние": СОСТОЯНИЕ_НЕ_ПОДТВЕРЖДЕНО,
                "проверка": проверка,
                "browser_evidence": browser_evidence,
                "применено": False,
            }

    исходник = _текущий_исходник(каталог_тестов, сессия)
    черновик = {"init.json": init_json, "test.feature": feature}
    ревизия_черновика = _ревизия(черновик)
    сессия.update(
        {
            "черновик": черновик,
            "ревизия_черновика": ревизия_черновика,
            "diff": _построить_diff(исходник, черновик),
            "browser_evidence": browser_evidence,
        }
    )

    if (
        browser_evidence is not None
        and browser_evidence["состояние"] == СОСТОЯНИЕ_ДЕФЕКТ_НАЙДЕН
    ):
        сессия["состояние"] = СОСТОЯНИЕ_ЖДЁТ_ПОДТВЕРЖДЕНИЯ_ДЕФЕКТА
        применено = False
    elif сессия["режим"] == "create":
        _создать_атомарно(каталог_тестов, сессия["тест"], черновик)
        сессия["состояние"] = СОСТОЯНИЕ_ПРИМЕНЕНА
        применено = True
    else:
        сессия["состояние"] = СОСТОЯНИЕ_ЖДЁТ_ПОДТВЕРЖДЕНИЯ
        применено = False

    _сохранить_сессию(каталог_сессий, сессия)
    return {
        **_публичная_сессия(сессия),
        "проверка": проверка,
        "browser_evidence": browser_evidence,
        "применено": применено,
    }


def применить(
    каталог_тестов: Path,
    каталог_сессий: Path,
    id_сессии: str,
    ревизия_черновика: str,
    подтвердить_дефект: bool = False,
) -> dict[str, Any]:
    """Применить подтверждённый update или подтверждённый реальный дефект."""
    сессия = _загрузить_сессию(каталог_сессий, id_сессии)
    ожидает_дефект = (
        сессия["состояние"] == СОСТОЯНИЕ_ЖДЁТ_ПОДТВЕРЖДЕНИЯ_ДЕФЕКТА
    )
    if (
        сессия["состояние"] != СОСТОЯНИЕ_ЖДЁТ_ПОДТВЕРЖДЕНИЯ
        and not ожидает_дефект
    ):
        raise ОшибкаАгентскогоAPI("сессия не ожидает подтверждения")
    if ожидает_дефект and not подтвердить_дефект:
        raise ОшибкаАгентскогоAPI(
            "обнаруженное расхождение требует 'подтвердить_дефект: true'"
        )
    if not ожидает_дефект and сессия["режим"] != "update":
        raise ОшибкаАгентскогоAPI("новый тест применяется автоматически при prepare")
    if ревизия_черновика != сессия["ревизия_черновика"]:
        raise ОшибкаАгентскогоAPI(
            "подтверждена неактуальная ревизия черновика; запросите diff снова"
        )

    _текущий_исходник(каталог_тестов, сессия)
    if сессия["режим"] == "create":
        _создать_атомарно(
            каталог_тестов,
            сессия["тест"],
            сессия["черновик"],
        )
    else:
        _обновить_атомарно(
            каталог_тестов / сессия["тест"],
            сессия["черновик"],
        )
    if ожидает_дефект:
        сессия["подтверждённый_дефект"] = {
            "ревизия_черновика": сессия["ревизия_черновика"],
            "расхождения": сессия["browser_evidence"]["расхождения"],
        }
    сессия["состояние"] = СОСТОЯНИЕ_ПРИМЕНЕНА
    _сохранить_сессию(каталог_сессий, сессия)
    return {**_публичная_сессия(сессия), "применено": True}


def _текущий_исходник(
    каталог_тестов: Path,
    сессия: dict[str, Any],
) -> dict[str, str] | None:
    цель = каталог_тестов.resolve() / сессия["тест"]
    существует = цель.exists()
    if сессия["режим"] == "create":
        текущий = None
        if существует:
            raise ОшибкаАгентскогоAPI(
                "конфликт: каталог нового теста появился после открытия сессии"
            )
    else:
        if not существует:
            raise ОшибкаАгентскогоAPI(
                "конфликт: тест удалён после открытия сессии"
            )
        текущий = _прочитать_пару(цель)
    if _ревизия(текущий) != сессия["базовая_ревизия"]:
        raise ОшибкаАгентскогоAPI(
            "конфликт: тест изменился после открытия сессии; откройте новую сессию"
        )
    return текущий


def _прочитать_пару(каталог: Path) -> dict[str, str]:
    файлы = (каталог / "init.json", каталог / "test.feature")
    if any(файл.is_symlink() for файл in файлы):
        raise ОшибкаАгентскогоAPI("файлы теста не могут быть символическими ссылками")
    try:
        return {
            файл.name: файл.read_text(encoding="utf-8")
            for файл in файлы
        }
    except OSError as ошибка:
        raise ОшибкаАгентскогоAPI(f"не удалось прочитать тест: {ошибка}") from ошибка


def _ревизия(файлы: dict[str, str] | None) -> str:
    хеш = hashlib.sha256()
    if файлы is None:
        хеш.update(b"<absent>")
    else:
        for имя in ("init.json", "test.feature"):
            хеш.update(имя.encode())
            хеш.update(b"\0")
            хеш.update(файлы[имя].encode())
            хеш.update(b"\0")
    return хеш.hexdigest()


def _построить_diff(
    исходник: dict[str, str] | None,
    черновик: dict[str, str],
) -> str:
    части = []
    for имя in ("init.json", "test.feature"):
        старое = "" if исходник is None else исходник[имя]
        части.extend(
            difflib.unified_diff(
                старое.splitlines(keepends=True),
                черновик[имя].splitlines(keepends=True),
                fromfile="/dev/null" if исходник is None else f"a/{имя}",
                tofile=f"b/{имя}",
            )
        )
    return "".join(части)


def _создать_атомарно(
    каталог_тестов: Path,
    имя: str,
    черновик: dict[str, str],
) -> None:
    каталог_тестов = каталог_тестов.resolve()
    каталог_тестов.mkdir(parents=True, exist_ok=True)
    временный = Path(
        tempfile.mkdtemp(prefix=".elemspec-agent-", dir=каталог_тестов)
    )
    try:
        for файл, содержимое in черновик.items():
            (временный / файл).write_text(содержимое, encoding="utf-8")
        os.rename(временный, каталог_тестов / имя)
    except OSError as ошибка:
        for файл in временный.iterdir():
            файл.unlink()
        временный.rmdir()
        raise ОшибкаАгентскогоAPI(f"не удалось создать тест: {ошибка}") from ошибка


def _обновить_атомарно(каталог: Path, черновик: dict[str, str]) -> None:
    исходник = _прочитать_пару(каталог)
    временные: dict[str, Path] = {}
    try:
        for имя, содержимое in черновик.items():
            дескриптор, путь = tempfile.mkstemp(
                prefix=f".{имя}.",
                dir=каталог,
                text=True,
            )
            with os.fdopen(дескриптор, "w", encoding="utf-8") as файл:
                файл.write(содержимое)
            временные[имя] = Path(путь)
        for имя in ("init.json", "test.feature"):
            os.replace(временные.pop(имя), каталог / имя)
    except OSError as ошибка:
        for путь in временные.values():
            путь.unlink(missing_ok=True)
        for имя, содержимое in исходник.items():
            (каталог / имя).write_text(содержимое, encoding="utf-8")
        raise ОшибкаАгентскогоAPI(f"не удалось обновить тест: {ошибка}") from ошибка


def _файл_сессии(каталог_сессий: Path, id_сессии: str) -> Path:
    try:
        нормализованный = str(uuid.UUID(id_сессии))
    except (ValueError, AttributeError) as ошибка:
        raise ОшибкаАгентскогоAPI("некорректный идентификатор сессии") from ошибка
    каталог_сессий = каталог_сессий.resolve()
    return каталог_сессий / f"{нормализованный}.json"


def _загрузить_сессию(
    каталог_сессий: Path,
    id_сессии: str,
) -> dict[str, Any]:
    файл = _файл_сессии(каталог_сессий, id_сессии)
    try:
        return json.loads(файл.read_text(encoding="utf-8"))
    except FileNotFoundError as ошибка:
        raise ОшибкаАгентскогоAPI("сессия не найдена") from ошибка
    except (OSError, json.JSONDecodeError) as ошибка:
        raise ОшибкаАгентскогоAPI(f"не удалось прочитать сессию: {ошибка}") from ошибка


def _сохранить_сессию(
    каталог_сессий: Path,
    сессия: dict[str, Any],
) -> None:
    каталог_сессий.mkdir(parents=True, exist_ok=True)
    файл = _файл_сессии(каталог_сессий, сессия["id"])
    дескриптор, путь = tempfile.mkstemp(
        prefix=".session.",
        dir=каталог_сессий,
        text=True,
    )
    временный = Path(путь)
    try:
        with os.fdopen(дескриптор, "w", encoding="utf-8") as поток:
            json.dump(сессия, поток, ensure_ascii=False, indent=2)
        os.replace(временный, файл)
    except OSError as ошибка:
        временный.unlink(missing_ok=True)
        raise ОшибкаАгентскогоAPI(f"не удалось сохранить сессию: {ошибка}") from ошибка


def _публичная_сессия(сессия: dict[str, Any]) -> dict[str, Any]:
    return {
        "сессия": сессия["id"],
        "тест": сессия["тест"],
        "режим": сессия["режим"],
        "состояние": сессия["состояние"],
        "ревизия_черновика": сессия["ревизия_черновика"],
        "diff": сессия["diff"],
        "browser_evidence": сессия.get("browser_evidence"),
        "подтверждённый_дефект": сессия.get("подтверждённый_дефект"),
    }
