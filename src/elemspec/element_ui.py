"""Устойчивые семантические локаторы веб-клиента 1С:Элемент."""

from __future__ import annotations

import re


КОМПОНЕНТ_ПУНКТА_НАВИГАЦИИ = "navigation-item"
КОМПОНЕНТ_МЕТКИ = "label"
СЕЛЕКТОР_ПУНКТА_НАВИГАЦИИ = (
    f'[data-component="{КОМПОНЕНТ_ПУНКТА_НАВИГАЦИИ}"]'
)
СЕЛЕКТОР_МЕТКИ = f'[data-component="{КОМПОНЕНТ_МЕТКИ}"]'
СЕЛЕКТОР_РЕДАКТИРУЕМОГО = (
    "input:not([type='hidden']):not([type='checkbox']):not([type='radio'])"
    ":not([type='button']):not([type='submit']):not([type='reset'])"
    ":not([type='file']):not([type='image']), textarea, [contenteditable='true']"
)
КОМПОНЕНТ_ТАБЛИЦЫ = "table"
КОМПОНЕНТ_СТРОКИ_ТАБЛИЦЫ = "table-row"
КОМПОНЕНТ_ЯЧЕЙКИ_ТАБЛИЦЫ = "table-cell"
КОМПОНЕНТ_КОМАНДЫ = "button"
РОЛЬ_ДИАЛОГА = "alertdialog"
ТЕСТ_ИД_ЗАГОЛОВКА_ФОРМЫ = "desktop-header-title"
СЕЛЕКТОР_ЗАГОЛОВКА_ДИАЛОГА = (
    "h1, h2, h3, h4, h5, h6, "
    "[data-component='title'], [data-testid$='title'], "
    "[data-testid*='title-']"
)
СЕЛЕКТОР_КОМАНДЫ = f'[data-component="{КОМПОНЕНТ_КОМАНДЫ}"]'
СЕЛЕКТОР_ТАБЛИЦЫ = f'[data-component="{КОМПОНЕНТ_ТАБЛИЦЫ}"]'
СЕЛЕКТОР_СТРОКИ_ТАБЛИЦЫ = (
    f'[data-component="{КОМПОНЕНТ_СТРОКИ_ТАБЛИЦЫ}"]'
)
ТЕСТ_ИД_ВЫПАДАЮЩЕГО_СПИСКА = "edit-dropdown-table"
ТЕСТ_ИД_СООБЩЕНИЯ_ПОЛЯ = "base-editable-message-information"


def пункт_навигации(страница, метка: str):
    """Найти ближайший navigation-item по точному тексту вложенного label."""
    точный_текст = re.compile(rf"^\s*{re.escape(метка)}\s*$")
    метки = страница.locator(СЕЛЕКТОР_МЕТКИ).filter(has_text=точный_текст)
    return метки.locator(
        f'xpath=ancestor::*[@data-component="{КОМПОНЕНТ_ПУНКТА_НАВИГАЦИИ}"][1]'
    )


def команда(страница, метка: str):
    """Найти платформенную команду-кнопку по точной вложенной label."""
    точный_текст = re.compile(rf"^\s*{re.escape(метка)}\s*$")
    метки = страница.locator(СЕЛЕКТОР_МЕТКИ).filter(has_text=точный_текст)
    return метки.locator(
        f'xpath=ancestor::*[@data-component="{КОМПОНЕНТ_КОМАНДЫ}"][1]'
    )


def команда_диалога(страница, метка: str):
    """Найти платформенную команду только внутри видимого модального диалога."""
    диалоги = страница.locator(f'[role="{РОЛЬ_ДИАЛОГА}"]:visible')
    точный_текст = re.compile(rf"^\s*{re.escape(метка)}\s*$")
    метки = диалоги.locator(СЕЛЕКТОР_МЕТКИ).filter(has_text=точный_текст)
    return метки.locator(
        f'xpath=ancestor::*[@data-component="{КОМПОНЕНТ_КОМАНДЫ}"][1]'
    )


def заголовок_формы(страница, заголовок: str):
    """Найти видимый платформенный заголовок текущей формы по точному тексту."""
    точный_текст = re.compile(rf"^\s*{re.escape(заголовок)}\s*$")
    return страница.locator(
        f'[data-testid="{ТЕСТ_ИД_ЗАГОЛОВКА_ФОРМЫ}"]:visible'
    ).filter(has_text=точный_текст)


def заголовок_диалога(страница, заголовок: str):
    """Найти точный заголовок только внутри видимого модального диалога."""
    диалоги = страница.locator(f'[role="{РОЛЬ_ДИАЛОГА}"]:visible')
    точный_текст = re.compile(rf"^\s*{re.escape(заголовок)}\s*$")
    заголовки = страница.locator(СЕЛЕКТОР_ЗАГОЛОВКА_ДИАЛОГА).filter(
        has_text=точный_текст
    )
    return диалоги.filter(has=заголовки).locator(
        СЕЛЕКТОР_ЗАГОЛОВКА_ДИАЛОГА
    ).filter(has_text=точный_текст)


def поле_компонента(страница, имя: str):
    """Найти текстовое поле внутри именованного компонента."""
    return страница.get_by_test_id(имя).locator(СЕЛЕКТОР_РЕДАКТИРУЕМОГО)


def сообщения_поля(страница, имя: str):
    """Найти сообщения валидации только внутри именованного компонента поля."""
    return страница.get_by_test_id(имя).get_by_test_id(ТЕСТ_ИД_СООБЩЕНИЯ_ПОЛЯ)


def значение_редактора(элемент) -> str:
    """Прочитать пользовательское значение input/textarea/contenteditable."""
    тег = элемент.evaluate("(node) => node.tagName.toLowerCase()")
    if тег in {"input", "textarea", "select"}:
        return str(элемент.input_value())
    if элемент.get_attribute("contenteditable") == "true":
        return str(элемент.inner_text())
    raise ValueError("элемент не является поддерживаемым редактором значения")


def таблица_компонента(страница, имя: str):
    """Найти платформенную таблицу внутри именованного компонента."""
    return страница.get_by_test_id(имя).locator(СЕЛЕКТОР_ТАБЛИЦЫ)


def строки_таблицы_по_значению(
    страница, имя_таблицы: str, колонка: str, значение: str
):
    """Найти строки именованной таблицы по точному тексту именованной колонки."""
    таблица = таблица_компонента(страница, имя_таблицы)
    строки = таблица.locator(СЕЛЕКТОР_СТРОКИ_ТАБЛИЦЫ)
    точный_текст = re.compile(rf"^\s*{re.escape(значение)}\s*$")
    # В filter(has=...) внутренний локатор вычисляется относительно каждой строки.
    # Если заранее привязать его к таблице, Playwright начнёт поиск с таблицы второй
    # раз и не увидит подходящую ячейку.
    ячейка = страница.get_by_test_id(колонка).filter(has_text=точный_текст)
    return строки.filter(has=ячейка)


def видимые_выпадающие_списки(страница):
    """Найти открытый платформенный список выбора значения поля."""
    return страница.locator(
        f'[data-testid="{ТЕСТ_ИД_ВЫПАДАЮЩЕГО_СПИСКА}"]:visible'
    )


def варианты_выпадающего_списка(страница, значение: str):
    """Найти строки открытого списка с точным пользовательским значением."""
    списки = видимые_выпадающие_списки(страница)
    строки = списки.locator(СЕЛЕКТОР_СТРОКИ_ТАБЛИЦЫ)
    точный_текст = re.compile(rf"^\s*{re.escape(значение)}\s*$")
    ячейка = страница.locator(
        f'[data-component="{КОМПОНЕНТ_ЯЧЕЙКИ_ТАБЛИЦЫ}"]'
    ).filter(has_text=точный_текст)
    return строки.filter(has=ячейка)


def логические_варианты(варианты):
    """Схлопнуть визуальные копии одной строки по платформенному row index.

    Веб-клиент может одновременно отрисовать одну строку несколько раз. Только
    одинаковый непустой ``data-row-index`` доказывает, что это одна логическая
    запись; одинакового пользовательского текста для этого недостаточно.
    """
    группы: dict[str, object] = {}
    без_индекса = []
    for индекс in range(варианты.count()):
        вариант = варианты.nth(индекс)
        row_index = вариант.get_attribute("data-row-index")
        if row_index is None or row_index == "":
            без_индекса.append(вариант)
        else:
            группы.setdefault(row_index, вариант)
    return [*группы.values(), *без_индекса]
