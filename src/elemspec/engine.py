СТАТУС_ОК = "ок"
СТАТУС_ПРОВАЛ = "провал"
СТАТУС_СЛОМАН = "сломан"
СТАТУС_ПРОПУЩЕН = "пропущен"


@dataclass
class РезультатШага:
    номер: int
    имя: str
    действие: str
    статус: str
    длительность_с: float = 0.0
    сообщение: str = ""
    подробности: str = ""
    снимок: str | None = None

    def в_словарь(self) -> dict[str, Any]:
        return {
            "номер": self.номер,
            "имя": self.имя,
            "действие": self.действие,
            "статус": self.статус,
            "длительность_с": round(self.длительность_с, 3),
            "сообщение": self.сообщение,
            "подробности": self.подробности,
            "снимок": self.снимок,
        }


@dataclass
class РезультатТеста:
    имя: str
    каталог: str
    статус: str
    длительность_с: float = 0.0
    сообщение: str = ""
    описание: str = ""
    запись: str | None = None
    путь_артефактов: str = ""  # относительно каталога отчёта: артефакты/<тест>/сценарий-N
    шаги: list[РезультатШага] = field(default_factory=list)

    def в_словарь(self) -> dict[str, Any]:
        return {
            "имя": self.имя,
            "каталог": self.каталог,
            "статус": self.статус,
            "длительность_с": round(self.длительность_с, 3),
            "сообщение": self.сообщение,
            "описание": self.описание,
            "запись": self.запись,
            "путь_артефактов": self.путь_артефактов,
            "шаги": [шаг.в_словарь() for шаг in self.шаги],
        }


@dataclass
class РезультатПрогона:
    начат: str
    длительность_с: float
    тесты: list[РезультатТеста]

    @property
    def итоги(self) -> dict[str, int]:
        свод = {
            "всего": len(self.тесты),
            СТАТУС_ОК: 0,
            СТАТУС_ПРОВАЛ: 0,
            СТАТУС_СЛОМАН: 0,
            СТАТУС_ПРОПУЩЕН: 0,
        }
        for тест in self.тесты:
            свод[тест.статус] = свод.get(тест.статус, 0) + 1
        return свод

    @property
    def успешен(self) -> bool:
        return all(
            тест.статус in (СТАТУС_ОК, СТАТУС_ПРОПУЩЕН) for тест in self.тесты
        )

    def в_словарь(self) -> dict[str, Any]:
        return {
            "начат": self.начат,
            "длительность_с": round(self.длительность_с, 3),
            "итоги": self.итоги,
            "успешен": self.успешен,
            "тесты": [тест.в_словарь() for тест in self.тесты],
        }


def _краткое(исключение: BaseException) -> str:
    текст = str(исключение).strip() or исключение.__class__.__name__
    return текст.splitlines()[0][:300]


def выполнить_тест(
    каталог: Path,
    каталог_отчёта: Path,
    видимый: bool = False,
    запись: str | None = None,
    курсор_режим: str | None = None,
) -> list[РезультатТеста]:
    """Прогоняет все сценарии функции. Результат - по записи на сценарий:
    сценарий и есть единица прогона, у каждого свой чистый контекст браузера
    (и предыстория, выполненная заново) - как принято в Gherkin.
    """
    старт = time.monotonic()
    try:
        политика = Проект.найти(старт=каталог).политика
        настройки = Настройки.прочитать(каталог)
        if запись:  # ключи командной строки перекрывают init.json
            настройки.запись.режим = запись
        if курсор_режим:
            настройки.курсор = курсор_режим
        тест = Тест.прочитать(настройки)
        if настройки.базовый_адрес:
            политика.проверить_url(настройки.базовый_адрес)
        for сценарий in тест.сценарии:
            for шаг in сценарий.шаги:
                for значение in шаг.аргументы.values():
                    if isinstance(значение, str) and значение.startswith(
                        ("http://", "https://")
                    ):
                        политика.проверить_url(значение)
    except (ОшибкаЗагрузки, ОшибкаПолитикиХостов, ОшибкаПроекта) as ош:
        return [РезультатТеста(
            имя=каталог.name,
            каталог=каталог.name,
            статус=СТАТУС_СЛОМАН,
            сообщение=str(ош),
            длительность_с=time.monotonic() - старт,
        )]

    if настройки.пропустить or "@пропустить" in тест.теги:
        return [РезультатТеста(
            имя=тест.имя,
            каталог=каталог.name,
            статус=СТАТУС_ПРОПУЩЕН,
            описание=тест.описание,
            сообщение="функция отключена (init.json 'пропустить' или тег @пропустить)",
        )]

    результаты: list[РезультатТеста] = []
    with sync_playwright() as playwright:
        тип = getattr(playwright, настройки.браузер.тип, None)
        if тип is None:
            return [РезультатТеста(
                имя=тест.имя,
                каталог=каталог.name,
                статус=СТАТУС_СЛОМАН,
                сообщение=f"неизвестный тип браузера '{настройки.браузер.тип}'",
                длительность_с=time.monotonic() - старт,
            )]

        браузер = тип.launch(
            headless=False if видимый else настройки.браузер.headless,
            slow_mo=настройки.браузер.замедление_мс,
        )
        try:
            for индекс, сценарий in enumerate(тест.сценарии, start=1):
                результаты.append(
                    _выполнить_сценарий(
                        браузер,
                        тест,
                        сценарий,
                        индекс,
                        каталог_отчёта,
                        видимый,
                        политика,
                    )
                )
        finally:
            браузер.close()
    return результаты


def _выполнить_сценарий(
    браузер,
    тест: Тест,
    сценарий,
    индекс: int,
    каталог_отчёта: Path,
    видимый: bool,
    политика: ПолитикаХостов,
) -> РезультатТеста:
    настройки = тест.настройки
    имя_каталога = настройки.каталог.name
    результат = РезультатТеста(
        имя=f"{тест.имя} › {сценарий.имя}",
        каталог=имя_каталога,
        статус=СТАТУС_ОК,
        описание=тест.описание if индекс == 1 else "",
        путь_артефактов=f"артефакты/{имя_каталога}/сценарий-{индекс}",
    )
    if сценарий.пропустить:
        результат.статус = СТАТУС_ПРОПУЩЕН
        результат.сообщение = "сценарий помечен тегом @пропустить"
        return результат

    старт = time.monotonic()
    каталог_артефактов = каталог_отчёта / результат.путь_артефактов
    пишем = настройки.запись.режим != ЗАПИСЬ_НЕТ
    параметры_контекста: dict[str, Any] = {
        "viewport": {
            "width": настройки.браузер.ширина,
            "height": настройки.браузер.высота,
        }
    }
    if пишем:
        # Писать можно только с самого начала: задним числом прогон не вернуть.
        # Поэтому в режиме 'провал' пишем всегда, а лишнее удаляем в конце.
        параметры_контекста["record_video_dir"] = str(каталог_артефактов / "черновик")
        параметры_контекста["record_video_size"] = {
            "width": настройки.запись.ширина or настройки.браузер.ширина,
            "height": настройки.запись.высота or настройки.браузер.высота,
        }
    контекст_браузера = браузер.new_context(**параметры_контекста)
    контекст_браузера.route("**/*", ОграничительНавигации(политика))
    if cursor.нужен(настройки.курсор, пишем, видимый):
        # Ставим до открытия страницы: init-скрипт применяется к новым документам,
        # а платформа Элемент перезагружает их на каждом разделе.
        контекст_браузера.add_init_script(cursor.СКРИПТ)
    страница = контекст_браузера.new_page()
    страница.set_default_timeout(настройки.таймаут_мс)
    контекст = actions.Контекст(
        страница=страница,
        настройки=настройки,
        каталог_артефактов=каталог_артефактов,
    )
    try:
        _прогнать_шаги(сценарий, контекст, результат, настройки.параметры)
    finally:
        результат.длительность_с = time.monotonic() - старт
        if пишем:
            результат.запись = _сохранить_запись(
                страница, контекст_браузера, настройки, результат, каталог_артефактов
            )
        else:
            контекст_браузера.close()
    return результат


def _сохранить_запись(
    страница,
    контекст_браузера,
    настройки: Настройки,
    результат: РезультатТеста,
    каталог_артефактов: Path,
) -> str | None:
    """Финализирует видео и решает, оставлять ли его. Запись - вещь вспомогательная:
    её проблемы не должны ронять тест, поэтому все сбои глушим.
    """
    оставить = настройки.запись.режим == ЗАПИСЬ_ВСЕГДА or результат.статус in (
        СТАТУС_ПРОВАЛ,
        СТАТУС_СЛОМАН,
    )
    try:
        видео = страница.video
        if видео is None:
            return None
        контекст_браузера.close()  # видео дописывается только при закрытии контекста
        исходник = Path(видео.path())
        if not оставить:
            видео.delete()
            return None
        итог = каталог_артефактов / "запись.webm"
        итог.parent.mkdir(parents=True, exist_ok=True)
        исходник.replace(итог)
        return итог.name
    except Exception:
        return None
    finally:
        черновик = каталог_артефактов / "черновик"
        if черновик.exists():
            shutil.rmtree(черновик, ignore_errors=True)


def _прогнать_шаги(
    сценарий, контекст: actions.Контекст, результат: РезультатТеста,
    параметры: dict[str, Any],
) -> None:
    прерван = False
    for шаг in сценарий.шаги:
        if прерван:
            результат.шаги.append(
                РезультатШага(
                    номер=шаг.номер,
                    имя=шаг.имя,
                    действие=шаг.действие,
                    статус=СТАТУС_ПРОПУЩЕН,
                    сообщение="не выполнялся - сценарий остановлен раньше",
                )
            )
            continue

        итог = _выполнить_шаг(шаг, контекст, параметры)
        результат.шаги.append(итог)

        if итог.статус in (СТАТУС_ПРОВАЛ, СТАТУС_СЛОМАН):
            результат.статус = итог.статус
            результат.сообщение = f"шаг {шаг.номер} «{шаг.имя}»: {итог.сообщение}"
            прерван = True


def _выполнить_шаг(
    шаг, контекст: actions.Контекст, параметры: dict[str, Any]
) -> РезультатШага:
    итог = РезультатШага(
        номер=шаг.номер, имя=шаг.имя, действие=шаг.действие, статус=СТАТУС_ОК
    )
    старт = time.monotonic()
    было_артефактов = len(контекст.артефакты)
    try:
        функция = actions.получить(шаг.действие)
        аргументы = подставить(шаг.аргументы, параметры)
        итог.сообщение = функция(контекст, аргументы) or "выполнено"
        if len(контекст.артефакты) > было_артефактов:
            # Шаг сам сделал снимок (действие 'скриншот') - показать его в отчёте,
            # иначе файл лежит на диске, а глазами его никто не увидит.
            итог.снимок = контекст.артефакты[-1]
    except actions.ОшибкаПроверки as ош:
        итог.статус = СТАТУС_ПРОВАЛ
        итог.сообщение = _краткое(ош)
        итог.снимок = _снять_безопасно(контекст, шаг.номер)
    except Exception as ош:
        итог.статус = СТАТУС_СЛОМАН
        итог.сообщение = _краткое(ош)
        итог.подробности = traceback.format_exc(limit=4)
        итог.снимок = _снять_безопасно(контекст, шаг.номер)
    итог.длительность_с = time.monotonic() - старт
    return итог


def _снять_безопасно(контекст: actions.Контекст, номер: int) -> str | None:
    """Снимок падения - лучший источник диагностики, но сам он тест ронять не должен."""
    try:
        return контекст.снимок(f"падение-шаг-{номер}")
    except Exception:
        return None


def выполнить_прогон(
    каталоги: list[Path],
    каталог_отчёта: Path,
    видимый: bool = False,
    запись: str | None = None,
    курсор_режим: str | None = None,
) -> РезультатПрогона:
    начат = datetime.now()
    старт = time.monotonic()
    тесты = [
        результат
        for каталог in каталоги
        for результат in выполнить_тест(каталог, каталог_отчёта, видимый, запись, курсор_режим)
    ]
    return РезультатПрогона(
        начат=начат.isoformat(timespec="seconds"),
        длительность_с=time.monotonic() - старт,
        тесты=тесты,
    )
