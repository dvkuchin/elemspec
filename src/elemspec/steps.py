"""Словарь фраз Gherkin: текст шага -> действие движка + аргументы.

Аналог step definitions в Cucumber, только фразы встроенные, а не пользовательские.
Фраза выбирает и способ адресации - лестница локаторов остаётся явной:

    элемент "X"             - имя компонента (data-testid), надёжно
    поле "X"               - редактируемый элемент внутри компонента X, надёжно
    пункт навигации "X"     - navigation-item по вложенному label, надёжно
    текст "X"               - видимый текст, приемлемо
    селектор "X"            - сырой CSS, технический долг

Голое `"X"` без слова-локатора означает `элемент "X"`.
"""

from __future__ import annotations

import re
from typing import Any


class НеизвестнаяФраза(Exception):
    """Шаг не совпал ни с одной фразой словаря."""


# Локатор внутри фразы: (элемент|поле|пункт навигации|текст|селектор)? "значение"
_ЛОК = r'(?:(элемент|поле|пункт навигации|текст|селектор)\s+)?"([^"]*)"'
_ВИДЫ = {
    None: "тест_ид",
    "элемент": "тест_ид",
    "поле": "поле_компонента",
    "пункт навигации": "пункт_навигации",
    "текст": "текст",
    "селектор": "селектор",
}


def _локатор(вид: str | None, значение: str) -> dict[str, str]:
    return {_ВИДЫ[вид]: значение}


# Каждая запись: (регулярка на ПОЛНЫЙ текст шага, действие, сборка аргументов).
# Регистр не важен, ключевое слово (Дано/Когда/Тогда/И) движком не различается -
# оно для человека: порядок и смысл шагов задаёт автор сценария.
_СЛОВАРЬ: list[tuple[re.Pattern[str], str, Any]] = []


def _фраза(шаблон: str, действие: str, аргументы) -> None:
    _СЛОВАРЬ.append((re.compile(f"^{шаблон}$", re.IGNORECASE), действие, аргументы))


# --- навигация --------------------------------------------------------------

_фраза(r'я открываю страницу\s+"([^"]*)"', "открыть",
       lambda г: {"адрес": г[0]})

_фраза(rf"я жду\s+{_ЛОК}", "ждать_элемент",
       lambda г: _локатор(г[0], г[1]))

_фраза(r"я жду\s+(\d+)\s*мс", "пауза",
       lambda г: {"мс": int(г[0])})

# --- проверки ---------------------------------------------------------------

_фраза(r'на странице есть текст\s+"([^"]*)"', "проверить_текст",
       lambda г: {"текст": г[0]})

_фраза(r'на странице нет текста\s+"([^"]*)"', "проверить_текст",
       lambda г: {"текст": г[0], "отсутствует": True})

_фраза(r'заголовок вкладки содержит\s+"([^"]*)"', "проверить_заголовок",
       lambda г: {"текст": г[0]})

_фраза(r'открылась форма\s+"([^"]*)"', "проверить_заголовок_формы",
       lambda г: {"заголовок_формы": г[0]})

_фраза(r'открылся диалог\s+"([^"]*)"', "проверить_заголовок_диалога",
       lambda г: {"заголовок_диалога": г[0]})

_фраза(r'адрес содержит\s+"([^"]*)"', "проверить_адрес",
       lambda г: {"адрес": г[0]})

_фраза(rf"виден\s+{_ЛОК}", "проверить_элемент",
       lambda г: {**_локатор(г[0], г[1]), "видимый": True})

_фраза(r'видна команда\s+"([^"]*)"', "проверить_элемент",
       lambda г: {"команда": г[0], "видимый": True})

_фраза(rf"есть\s+{_ЛОК}", "проверить_элемент",
       lambda г: _локатор(г[0], г[1]))

_фраза(rf"{_ЛОК}\s+отсутствует", "проверить_элемент",
       lambda г: {**_локатор(г[0], г[1]), "количество": 0})

_фраза(rf"{_ЛОК}\s+виден ровно\s+(\d+)\s+раз(?:а)?", "проверить_элемент",
       lambda г: {**_локатор(г[0], г[1]), "количество": int(г[2]), "видимый": True})

_фраза(rf"{_ЛОК}\s+встречается ровно\s+(\d+)\s+раз(?:а)?", "проверить_элемент",
       lambda г: {**_локатор(г[0], г[1]), "количество": int(г[2])})

_фраза(rf"{_ЛОК}\s+доступен", "проверить_доступность",
       lambda г: {**_локатор(г[0], г[1]), "доступен": True})

_фраза(rf"{_ЛОК}\s+недоступен", "проверить_доступность",
       lambda г: {**_локатор(г[0], г[1]), "доступен": False})

_фраза(r'команда\s+"([^"]*)"\s+доступна', "проверить_доступность",
       lambda г: {"команда": г[0], "доступен": True})

_фраза(r'команда\s+"([^"]*)"\s+недоступна', "проверить_доступность",
       lambda г: {"команда": г[0], "доступен": False})

_фраза(r'поле\s+"([^"]*)"\s+имеет значение\s+"([^"]*)"',
       "проверить_значение_поля",
       lambda г: {"поле_компонента": г[0], "ожидаемое": г[1]})

_фраза(r'поле\s+"([^"]*)"\s+пусто', "проверить_значение_поля",
       lambda г: {"поле_компонента": г[0], "ожидаемое": ""})

_фраза(r'поле\s+"([^"]*)"\s+имеет ошибку\s+"([^"]*)"',
       "проверить_ошибку_поля",
       lambda г: {"поле_компонента": г[0], "ошибка": г[1]})

_фраза(
    r'в таблице\s+"([^"]*)",?\s+есть строка,?\s+где колонка\s+'
    r'"([^"]*)"\s+имеет значение\s+"([^"]*)"',
    "проверить_строки_таблицы",
    lambda г: {"таблица": г[0], "колонка": г[1], "значение_ячейки": г[2]},
)

_фраза(
    r'в таблице\s+"([^"]*)",?\s+нет строки,?\s+где колонка\s+'
    r'"([^"]*)"\s+имеет значение\s+"([^"]*)"',
    "проверить_строки_таблицы",
    lambda г: {
        "таблица": г[0],
        "колонка": г[1],
        "значение_ячейки": г[2],
        "количество": 0,
    },
)

