СОСТОЯНИЕ_ЗАВЕРШЕНА = "COMPLETE"
СОСТОЯНИЕ_ЗАВЕРШЕНА_С_ПРОБЕЛАМИ = "COMPLETE_WITH_GAPS"
СОСТОЯНИЕ_ДЕФЕКТ_ПОДТВЕРЖДЁН = "BUG_CONFIRMED"
СОСТОЯНИЕ_ДОКАЗАТЕЛЬСТВО_НЕВОЗМОЖНО = "PROOF_UNAVAILABLE"
_МАРКЕР = "__ELEMPWT_NEGATIVE_"
_ТЗ = re.compile(r"^\s*#\s*ТЗ:\s*(.+?)\s*$", re.IGNORECASE)
_ССЫЛКА_GAP = re.compile(r"^engine-gap:([a-z0-9]+(?:-[a-z0-9]+)*)(?:\s|$)")

Runner = Callable[[Path, Path], dict[str, Any]]


def доказать_красный(
    каталог_тестов: Path,
    каталог_сессий: Path,
    каталог_отчётов: Path,
    id_сессии: str,
    runner: Runner | None = None,
) -> dict[str, Any]:
    """Выполнить полный протокол, не изменяя рабочие файлы теста."""
    runner = runner or _выполнить
    сессия = _загрузить_сессию(каталог_сессий, id_сессии)
    if сессия["состояние"] != СОСТОЯНИЕ_ПРИМЕНЕНА:
        raise ОшибкаАгентскогоAPI(
            "доказательство доступно только после применения сессии"
        )

    тест = каталог_тестов.resolve() / сессия["тест"]
    текущий = _прочитать_пару(тест)
    if _ревизия(текущий) != сессия["ревизия_черновика"]:
        raise ОшибкаАгентскогоAPI(
            "тест изменился после применения сессии; откройте новую сессию"
        )
    gaps = _проверить_gaps(
        текущий["test.feature"],
        тест.parents[1] / "engine-gaps",
        сессия["тест"],
    )
    if gaps["незарегистрированные"]:
        return _неудача(
            каталог_сессий,
            сессия,
            "GAPS_NOT_REGISTERED",
            "каждый '# ТЗ:' должен ссылаться на зарегистрированный engine gap",
            {"gaps": gaps},
        )

    корень_отчётов = (
        каталог_отчётов
        / "agent"
        / сессия["id"]
        / datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    )
    исходный_зелёный = runner(тест, корень_отчётов / "01-green")
    if not _зелёный(исходный_зелёный):
        if _подтверждает_дефект(исходный_зелёный, сессия):
            сессия["состояние"] = СОСТОЯНИЕ_ДЕФЕКТ_ПОДТВЕРЖДЁН
            сессия["доказательство"] = {
                "исходный_красный": исходный_зелёный,
                "gaps": gaps,
                "подтверждённый_дефект": сессия["подтверждённый_дефект"],
            }
            _сохранить_сессию(каталог_сессий, сессия)
            return {
                "сессия": сессия["id"],
                "тест": сессия["тест"],
                "состояние": СОСТОЯНИЕ_ДЕФЕКТ_ПОДТВЕРЖДЁН,
                **сессия["доказательство"],
            }
        return _неудача(
            каталог_сессий,
            сессия,
            "ORIGINAL_NOT_GREEN",
            "исходный тест не прошёл; доказывать красный пока нечему",
            {"исходный_зелёный": исходный_зелёный},
        )

    мутация = выбрать_мутацию(текущий["test.feature"])
    if мутация is None:
        return _неудача(
            каталог_сессий,
            сессия,
            СОСТОЯНИЕ_ДОКАЗАТЕЛЬСТВО_НЕВОЗМОЖНО,
            "в тесте нет поддерживаемой проверки для негативной мутации",
            {"исходный_зелёный": исходный_зелёный},
        )

    мутированный = {
        "init.json": текущий["init.json"],
        "test.feature": мутация["feature"],
    }
    with tempfile.TemporaryDirectory(prefix="elemspec-negative-") as временный:
        корень = Path(временный)
        shutil.copy2(
            тест.parents[1] / "elemspec.toml",
            корень / "elemspec.toml",
        )
        временный_тест = корень / "tests" / сессия["тест"]
        временный_тест.mkdir(parents=True)
        for имя, содержимое in мутированный.items():
            (временный_тест / имя).write_text(содержимое, encoding="utf-8")
        красный = runner(временный_тест, корень_отчётов / "02-red")

    if not _доказанный_красный(красный):
        return _неудача(
            каталог_сессий,
            сессия,
            "RED_NOT_CONFIRMED",
            "негативная мутация не дала чистый провал со снимком",
            {
                "исходный_зелёный": исходный_зелёный,
                "мутация": _публичная_мутация(мутация),
                "красный": красный,
            },
        )

    итоговый_зелёный = runner(тест, корень_отчётов / "03-green-final")
    if not _зелёный(итоговый_зелёный):
        return _неудача(
            каталог_сессий,
            сессия,
            "FINAL_NOT_GREEN",
            "оригинальный тест не прошёл после доказательства красного",
            {
                "исходный_зелёный": исходный_зелёный,
                "мутация": _публичная_мутация(мутация),
                "красный": красный,
                "итоговый_зелёный": итоговый_зелёный,
            },
        )

    итоговое_состояние = (
        СОСТОЯНИЕ_ЗАВЕРШЕНА_С_ПРОБЕЛАМИ
        if gaps["зарегистрированные"]
        else СОСТОЯНИЕ_ЗАВЕРШЕНА
    )
    сессия["состояние"] = итоговое_состояние
    сессия["доказательство"] = {
        "исходный_зелёный": исходный_зелёный,
        "мутация": _публичная_мутация(мутация),
        "красный": красный,
        "итоговый_зелёный": итоговый_зелёный,
        "gaps": gaps,
    }
    _сохранить_сессию(каталог_сессий, сессия)
    return {
        "сессия": сессия["id"],
        "тест": сессия["тест"],
        "состояние": итоговое_состояние,
        **сессия["доказательство"],
    }


def выбрать_мутацию(feature: str) -> dict[str, Any] | None:
    """Выбрать первую проверку, которую можно детерминированно испортить."""
    документ = Parser().parse(feature)
    функция = документ.get("feature")
    if not функция:
        return None
    for дитя in функция["children"]:
        узел = дитя.get("background") or дитя.get("scenario")
        if not узел:
            continue
        for сырой_шаг in узел["steps"]:
            текст = сырой_шаг["text"]
            try:
                действие, аргументы = steps.разобрать(текст)
            except steps.НеизвестнаяФраза:
                continue
            мутированный = _мутировать_текст_шага(текст, действие, аргументы)
            if мутированный is None:
                continue
            номер = сырой_шаг["location"]["line"]
            строки = feature.splitlines(keepends=True)
            исходная_строка = строки[номер - 1]
            строки[номер - 1] = исходная_строка.replace(
                текст,
                мутированный,
                1,
            )
            return {
                "feature": "".join(строки),
                "строка": номер,
                "действие": действие,
                "исходная_фраза": текст,
                "мутированная_фраза": мутированный,
            }
    return None


def _мутировать_текст_шага(
    текст: str,
    действие: str,
    аргументы: dict[str, Any],
) -> str | None:
    суффикс = f"{_МАРКЕР}{uuid.uuid4().hex}"
    if действие == "проверить_текст":
        if аргументы.get("отсутствует"):
            return None
        return _добавить_к_кавычкам(текст, 0, суффикс)
    if действие in {"проверить_заголовок", "проверить_адрес"}:
        return _добавить_к_кавычкам(текст, 0, суффикс)
    if действие == "клик_открывает_вкладку":
        return _добавить_к_кавычкам(текст, 1, суффикс)
    if действие == "проверить_элемент":
        if аргументы.get("количество") == 0:
            if текст.endswith(" отсутствует"):
                return текст.removesuffix(" отсутствует") + " виден ровно 1 раз"
            return re.sub(r"ровно\s+0\s+раз(?:а)?$", "ровно 1 раз", текст)
        return _добавить_к_кавычкам(текст, 0, суффикс)
    return None


def _добавить_к_кавычкам(текст: str, индекс: int, суффикс: str) -> str | None:
    совпадения = list(re.finditer(r'"([^"]*)"', текст))
    if индекс >= len(совпадения):
        return None
    совпадение = совпадения[индекс]
    return (
        текст[:совпадение.end(1)]
        + суффикс
        + текст[совпадение.end(1):]
    )


def _выполнить(каталог_теста: Path, каталог_отчёта: Path) -> dict[str, Any]:
    прогон = выполнить_прогон(
        [каталог_теста],
        каталог_отчёта,
        запись="провал",
    )
    файл_json, файл_html = записать(прогон, каталог_отчёта)
    результат = прогон.в_словарь()
    результат["report_json"] = str(файл_json)
    результат["report_html"] = str(файл_html)
    return результат


def _зелёный(результат: dict[str, Any]) -> bool:
    тесты = результат.get("тесты") or []
    допустимые = {СТАТУС_ОК, СТАТУС_ПРОПУЩЕН}
    return bool(тесты) and any(
        тест.get("статус") == СТАТУС_ОК for тест in тесты
    ) and all(тест.get("статус") in допустимые for тест in тесты)


def _доказанный_красный(результат: dict[str, Any]) -> bool:
    тесты = результат.get("тесты") or []
    провалы = [тест for тест in тесты if тест.get("статус") == СТАТУС_ПРОВАЛ]
    другие_ошибки = [
        тест
        for тест in тесты
        if тест.get("статус") not in {СТАТУС_ОК, СТАТУС_ПРОВАЛ, СТАТУС_ПРОПУЩЕН}
    ]
    есть_снимок = any(
        шаг.get("статус") == СТАТУС_ПРОВАЛ and шаг.get("снимок")
        for тест in провалы
        for шаг in тест.get("шаги", [])
    )
    return bool(провалы) and not другие_ошибки and есть_снимок


def _подтверждает_дефект(
    результат: dict[str, Any],
    сессия: dict[str, Any],
) -> bool:
    подтверждение = сессия.get("подтверждённый_дефект")
    if not isinstance(подтверждение, dict):
        return False
    ожидаемые_фразы = {
        расхождение.get("фраза")
        for расхождение in подтверждение.get("расхождения", [])
        if расхождение.get("фраза")
    }
    провальные_шаги = [
        шаг
        for тест in результат.get("тесты") or []
        if тест.get("статус") == СТАТУС_ПРОВАЛ
        for шаг in тест.get("шаги", [])
        if шаг.get("статус") == СТАТУС_ПРОВАЛ
    ]
    недопустимые_статусы = [
        тест.get("статус")
        for тест in результат.get("тесты") or []
        if тест.get("статус")
        not in {СТАТУС_ОК, СТАТУС_ПРОВАЛ, СТАТУС_ПРОПУЩЕН}
    ]
    return (
        bool(провальные_шаги)
        and not недопустимые_статусы
        and all(
            шаг.get("имя") in ожидаемые_фразы
            and bool(шаг.get("снимок"))
            for шаг in провальные_шаги
        )
    )


def _неудача(
    каталог_сессий: Path,
    сессия: dict[str, Any],
    состояние: str,
    сообщение: str,
    подробности: dict[str, Any],
) -> dict[str, Any]:
    # Не закрываем APPLIED-сессию: сетевой или инфраструктурный сбой можно
    # перепроверить вручную. Автоматических ретраев нет — они маскируют дефекты.
    сессия["последняя_попытка_доказательства"] = {
        "состояние": состояние,
        "сообщение": сообщение,
        **подробности,
    }
    _сохранить_сессию(каталог_сессий, сессия)
    return {
        "сессия": сессия["id"],
        "тест": сессия["тест"],
        "состояние": состояние,
        "сообщение": сообщение,
        **подробности,
    }


def _публичная_мутация(мутация: dict[str, Any]) -> dict[str, Any]:
    return {
        ключ: значение
        for ключ, значение in мутация.items()
        if ключ != "feature"
    }


def _проверить_gaps(
    feature: str,
    каталог: Path,
    имя_теста: str,
) -> dict[str, list[Any]]:
    зарегистрированные = []
    незарегистрированные = []
    for номер, строка in enumerate(feature.splitlines(), start=1):
        тз = _ТЗ.match(строка)
        if not тз:
            continue
        ссылка = _ССЫЛКА_GAP.match(тз.group(1))
        if not ссылка:
            незарегистрированные.append(
                {"строка": номер, "причина": "нет ссылки engine-gap:<id>"}
            )
            continue
        id_gap = ссылка.group(1)
        файл = каталог / f"{id_gap}.json"
        try:
            данные = json.loads(файл.read_text(encoding="utf-8"))
        except (FileNotFoundError, json.JSONDecodeError, OSError):
            незарегистрированные.append(
                {
                    "строка": номер,
                    "id": id_gap,
                    "причина": "файл gap отсутствует или повреждён",
                }
            )
            continue
        try:
            _валидировать(данные)
        except ОшибкаАгентскогоAPI as ошибка:
            незарегистрированные.append(
                {
                    "строка": номер,
                    "id": id_gap,
                    "причина": f"невалидное ТЗ: {ошибка}",
                }
            )
            continue
        if данные.get("id") != id_gap:
            незарегистрированные.append(
                {
                    "строка": номер,
                    "id": id_gap,
                    "причина": "id внутри файла не совпадает",
                }
            )
            continue
        if имя_теста not in данные.get("связанные_тесты", []):
            незарегистрированные.append(
                {
                    "строка": номер,
                    "id": id_gap,
                    "причина": "gap не связан с этим тестом",
                }
            )
            continue
        зарегистрированные.append({"строка": номер, "id": id_gap})
    return {
        "зарегистрированные": зарегистрированные,
        "незарегистрированные": незарегистрированные,
    }
