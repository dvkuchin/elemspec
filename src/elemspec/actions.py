class ОшибкаПроверки(AssertionError):
    """Проверка не выполнилась - тест провален по существу, а не технически."""


class ОшибкаДействия(Exception):
    """Действие описано неверно - нет обязательного аргумента, неизвестное имя."""


@dataclass
class Контекст:
    страница: Page
    настройки: Настройки
    каталог_артефактов: Path
    артефакты: list[str] = field(default_factory=list)

    def снимок(self, имя: str) -> str:
        """Пишет png в каталог отчёта, возвращает имя файла для ссылки из отчёта."""
        файл = self.каталог_артефактов / f"{имя}.png"
        файл.parent.mkdir(parents=True, exist_ok=True)
        self.страница.screenshot(path=str(файл), full_page=True)
        self.артефакты.append(файл.name)
        return файл.name


Действие = Callable[[Контекст, dict[str, Any]], str | None]
_РЕЕСТР: dict[str, Действие] = {}


def действие(имя: str) -> Callable[[Действие], Действие]:
    def регистратор(функция: Действие) -> Действие:
        _РЕЕСТР[имя] = функция
        return функция

    return регистратор


def получить(имя: str) -> Действие:
    if имя not in _РЕЕСТР:
        известные = ", ".join(sorted(_РЕЕСТР))
        raise ОшибкаДействия(f"неизвестное действие '{имя}'. Известные: {известные}")
    return _РЕЕСТР[имя]


def список_действий() -> list[str]:
    return sorted(_РЕЕСТР)


def _обязательный(аргументы: dict[str, Any], *имена: str) -> Any:
    for имя in имена:
        if аргументы.get(имя) not in (None, ""):
            return аргументы[имя]
    raise ОшибкаДействия(f"не указан обязательный аргумент '{имена[0]}'")


def нормализовать(текст: str) -> str:
    """Схлопывает пробелы/переносы/NBSP - вёрстка не должна ломать поиск текста."""
    return re.sub(r"\s+", " ", (текст or "").replace(" ", " ")).strip()


def _база(контекст: Контекст, аргументы: dict[str, Any]):
    """Лестница локаторов: testid/платформенный компонент → текст → CSS.

    Возвращает локатор на ВСЕ совпадения (для подсчёта) плюс тексты для сообщений.
    """
    if аргументы.get("поле_компонента"):
        имя = str(аргументы["поле_компонента"])
        база = поле_компонента(контекст.страница, имя)
        источник = f"поле '{имя}'"
        подсказка = (
            " Ожидается именованный data-testid компонента с ровно одним"
            " вложенным текстовым input, textarea или contenteditable."
        )
    elif аргументы.get("команда"):
        метка = str(аргументы["команда"])
        база = команда(контекст.страница, метка)
        источник = f"команда '{метка}'"
        подсказка = (
            " Ожидается data-component='button' с точной вложенной "
            "меткой data-component='label'."
        )
    elif аргументы.get("пункт_навигации"):
        метка = str(аргументы["пункт_навигации"])
        база = пункт_навигации(контекст.страница, метка)
        источник = f"пункт навигации '{метка}'"
        подсказка = (
            " Ожидается data-component='navigation-item' с точной вложенной "
            "меткой data-component='label'."
        )
    elif аргументы.get("тест_ид"):
        база = контекст.страница.get_by_test_id(str(аргументы["тест_ид"]))
        источник = f"тест_ид '{аргументы['тест_ид']}'"
        подсказка = (
            " Если компонента с таким именем нет - возможно, он не назван в исходниках"
            " (платформа отдаёт в data-testid имя компонента); попросите разработчика"
            " задать имя."
        )
    elif аргументы.get("текст"):
        база = контекст.страница.get_by_text(str(аргументы["текст"]), exact=False)
        источник = f"текст '{аргументы['текст']}'"
        подсказка = ""
    elif аргументы.get("селектор"):
        база = контекст.страница.locator(str(аргументы["селектор"]))
        источник = f"селектор '{аргументы['селектор']}'"
        подсказка = ""
    else:
        raise ОшибкаДействия(
            "нужен аргумент 'поле_компонента', 'команда', 'пункт_навигации',"
            " 'тест_ид', 'текст' или 'селектор'"
        )
    return база, источник, подсказка


def _элемент(контекст: Контекст, аргументы: dict[str, Any]):
    """Ровно один элемент - для действий, которые с ним взаимодействуют.

    Клик по одному из девяти совпадений хуже честной ошибки: молча выбранный
    'первый попавшийся' даёт тест, который зеленеет не по той причине.
    Уточнить выбор можно аргументом 'номер'.
    """
    база, источник, подсказка = _база(контекст, аргументы)

    номер = аргументы.get("номер")
    if номер is not None:
        return база.nth(int(номер) - 1)

    try:
        база.first.wait_for(state="attached")
    except Exception as ош:
        raise ОшибкаДействия(f"{источник}: элемент не найден.{подсказка}") from ош

    количество = база.count()
    if количество > 1:
        raise ОшибкаДействия(
            f"{источник}: найдено элементов - {количество}, неясно с каким работать."
            " Уточните аргументом 'номер' или попросите разработчика задать компоненту"
            " уникальное имя (автоимена вида 'Надпись6' повторяются по всей странице)."
        )
    return база.first


