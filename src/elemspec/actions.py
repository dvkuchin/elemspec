"""Реестр действий теста. Каждое действие - функция (Контекст, аргументы) -> str|None.

Возвращённая строка попадает в отчёт как результат шага. Провал - исключение
ОшибкаПроверки (проверка не прошла) или любое исключение Playwright (шаг сломался).
"""

