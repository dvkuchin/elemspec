@действие("выбрать_значение_поля")
def _выбрать_значение_поля(
    контекст: Контекст, аргументы: dict[str, Any]
) -> str:
    значение = str(_обязательный(аргументы, "значение"))
    поле = _элемент(контекст, аргументы)
    поле.click()

    списки = видимые_выпадающие_списки(контекст.страница)
    try:
        списки.first.wait_for(state="visible")
    except Exception as ошибка:
        raise ОшибкаДействия(
            f"поле '{аргументы.get('поле_компонента', '')}': "
            "выпадающий список выбора не открылся"
        ) from ошибка
    количество_списков = списки.count()
    if количество_списков != 1:
        raise ОшибкаДействия(
            f"открыто выпадающих списков — {количество_списков}, ожидался один"
        )

    варианты = варианты_выпадающего_списка(контекст.страница, значение)
    количество = варианты.count()
    if количество == 0:
        raise ОшибкаДействия(
            f"в выпадающем списке нет значения '{значение}'"
        )
    if количество > 1:
        raise ОшибкаДействия(
            f"в выпадающем списке значение '{значение}' найдено "
            f"в {количество} строках, выбор неоднозначен"
        )
    варианты.first.click()

    предел = time.monotonic() + контекст.настройки.таймаут_мс / 1000
    фактическое = значение_редактора(поле)
    while фактическое != значение and time.monotonic() < предел:
        контекст.страница.wait_for_timeout(100)
        фактическое = значение_редактора(поле)
    if фактическое != значение:
        raise ОшибкаПроверки(
            f"после выбора поле имеет значение '{фактическое}', "
            f"ожидалось '{значение}'"
        )
    return f"выбрано значение: '{значение}'"


@действие("нажать_клавишу")
def _нажать_клавишу(контекст: Контекст, аргументы: dict[str, Any]) -> str:
    клавиша = str(_обязательный(аргументы, "клавиша"))
    контекст.страница.keyboard.press(клавиша)
    return f"нажата клавиша {клавиша}"


@действие("скриншот")
def _скриншот(контекст: Контекст, аргументы: dict[str, Any]) -> str:
    имя = str(аргументы.get("файл") or f"снимок-{len(контекст.артефакты) + 1}")
    return f"снимок: {контекст.снимок(имя)}"
