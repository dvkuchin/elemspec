@действие("открыть")
def _открыть(контекст: Контекст, аргументы: dict[str, Any]) -> str:
    адрес = str(_обязательный(аргументы, "адрес"))
    if not адрес.startswith(("http://", "https://")):
        база = контекст.настройки.базовый_адрес
        if not база:
            raise ОшибкаДействия(
                f"адрес '{адрес}' относительный, а 'базовый_адрес' в init.json не задан"
            )
        адрес = f"{база}/{адрес.lstrip('/')}"
    ответ = контекст.страница.goto(
        адрес, wait_until=str(аргументы.get("состояние", "load"))
    )
    статус = ответ.status if ответ else "нет ответа"
    if ответ and ответ.status >= 400:
        raise ОшибкаПроверки(f"{адрес} - HTTP {ответ.status}")
    return f"{адрес} - HTTP {статус}"


@действие("ждать_загрузку")
def _ждать_загрузку(контекст: Контекст, аргументы: dict[str, Any]) -> str:
    состояние = str(аргументы.get("состояние", "networkidle"))
    контекст.страница.wait_for_load_state(состояние)
    return f"состояние '{состояние}' достигнуто"


@действие("ждать_элемент")
def _ждать_элемент(контекст: Контекст, аргументы: dict[str, Any]) -> str:
    база, источник, подсказка = _база(контекст, аргументы)
    состояние = str(аргументы.get("состояние", "visible"))
    try:
        база.first.wait_for(state=состояние)
    except Exception as ош:
        raise ОшибкаДействия(
            f"{источник}: не дождались состояния '{состояние}'.{подсказка}"
        ) from ош
    return f"элемент в состоянии '{состояние}'"


@действие("пауза")
def _пауза(контекст: Контекст, аргументы: dict[str, Any]) -> str:
    мс = int(_обязательный(аргументы, "мс"))
    контекст.страница.wait_for_timeout(мс)
    return f"ожидание {мс} мс"


