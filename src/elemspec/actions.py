@действие("проверить_текст")
def _проверить_текст(контекст: Контекст, аргументы: dict[str, Any]) -> str:
    ожидаемый = нормализовать(str(_обязательный(аргументы, "текст")))
    отсутствует = булево(аргументы.get("отсутствует"))
    if not отсутствует:
        # Дожидаемся появления текста, а не гонимся с отрисовкой: на Элементе
        # networkidle не наступает, полагаться на «страница уже дорисована» нельзя.
        # Ждём по нормализованному body (не get_by_text: искомая фраза может быть
        # склеена из нескольких элементов). Не дождались - честный провал ниже.
        try:
            контекст.страница.wait_for_function(
                "т => document.body && document.body.innerText"
                ".replace(/\\u00a0/g, ' ').replace(/\\s+/g, ' ').includes(т)",
                arg=ожидаемый,
            )
        except Exception:
            pass
    содержимое = нормализовать(контекст.страница.inner_text("body"))
    найден = ожидаемый in содержимое
    if отсутствует and найден:
        raise ОшибкаПроверки(f"текст найден, хотя не должен: '{ожидаемый}'")
    if not отсутствует and not найден:
        raise ОшибкаПроверки(f"текст не найден на странице: '{ожидаемый}'")
    return f"текст {'отсутствует' if отсутствует else 'найден'}: '{ожидаемый}'"


@действие("проверить_заголовок")
def _проверить_заголовок(контекст: Контекст, аргументы: dict[str, Any]) -> str:
    ожидаемый = str(_обязательный(аргументы, "текст"))
    фактический = контекст.страница.title()
    точно = булево(аргументы.get("точно"))
    совпало = фактический == ожидаемый if точно else ожидаемый in фактический
    if not совпало:
        raise ОшибкаПроверки(
            f"заголовок '{фактический}' не соответствует ожидаемому '{ожидаемый}'"
        )
    return f"заголовок: '{фактический}'"


@действие("проверить_адрес")
def _проверить_адрес(контекст: Контекст, аргументы: dict[str, Any]) -> str:
    ожидаемый = str(_обязательный(аргументы, "адрес"))
    фактический = контекст.страница.url
    if ожидаемый not in фактический:
        raise ОшибкаПроверки(f"адрес '{фактический}' не содержит '{ожидаемый}'")
    return f"адрес: {фактический}"


@действие("проверить_элемент")
def _проверить_элемент(контекст: Контекст, аргументы: dict[str, Any]) -> str:
    база, источник, подсказка = _база(контекст, аргументы)
    ожидаемое = аргументы.get("количество")
    видимый = булево(аргументы.get("видимый"))

    # Ждём того, что проверяем, иначе проверка гонится с отрисовкой и мигает на CI.
    # Для 'количество: 0' это ОТСУТСТВИЕ: ждать появления бессмысленно - на здоровом
    # приложении такой шаг всегда упирался бы в полный таймаут.
    ждём_отсутствия = ожидаемое is not None and int(ожидаемое) == 0
    if ждём_отсутствия:
        состояние = "hidden" if видимый else "detached"
    else:
        состояние = "visible" if видимый else "attached"
    try:
        база.first.wait_for(state=состояние)
    except Exception:
        pass
    количество = (
        len([э for э in база.all() if э.is_visible()]) if видимый else база.count()
    )
    что = "видимых элементов" if видимый else "элементов"
    if ожидаемое is not None and количество != int(ожидаемое):
        raise ОшибкаПроверки(
            f"{источник}: найдено {что} - {количество}, ожидалось {ожидаемое}.{подсказка}"
        )
    if ожидаемое is None and количество == 0:
        raise ОшибкаПроверки(f"{источник}: элемент не найден.{подсказка}")
    return f"{источник}: найдено {что} - {количество}"


@действие("проверить_значение_поля")
def _проверить_значение_поля(
    контекст: Контекст, аргументы: dict[str, Any]
) -> str:
    ожидаемое = str(аргументы.get("ожидаемое", ""))
    элемент = _элемент(контекст, аргументы)
    предел = time.monotonic() + контекст.настройки.таймаут_мс / 1000
    фактическое = значение_редактора(элемент)
    while фактическое != ожидаемое and time.monotonic() < предел:
        контекст.страница.wait_for_timeout(100)
        фактическое = значение_редактора(элемент)
    if фактическое != ожидаемое:
        имя = аргументы.get("поле_компонента", "")
        raise ОшибкаПроверки(
            f"поле '{имя}': значение '{фактическое}', ожидалось '{ожидаемое}'"
        )
    return f"значение поля: '{фактическое}'"


@действие("проверить_строки_таблицы")
def _проверить_строки_таблицы(
    контекст: Контекст, аргументы: dict[str, Any]
) -> str:
    имя = str(_обязательный(аргументы, "таблица"))
    колонка = str(_обязательный(аргументы, "колонка"))
    значение = str(_обязательный(аргументы, "значение_ячейки"))
    ожидаемое = аргументы.get("количество")
    строки = строки_таблицы_по_значению(
        контекст.страница, имя, колонка, значение
    )
    if ожидаемое is None:
        try:
            строки.first.wait_for(state="visible")
        except Exception:
            pass
        количество = строки.count()
        if количество == 0:
            raise ОшибкаПроверки(
                f"таблица '{имя}': не найдена строка, где колонка "
                f"'{колонка}' имеет значение '{значение}'"
            )
    else:
        предел = time.monotonic() + контекст.настройки.таймаут_мс / 1000
        количество = строки.count()
        while количество != int(ожидаемое) and time.monotonic() < предел:
            контекст.страница.wait_for_timeout(100)
            количество = строки.count()
        if количество != int(ожидаемое):
            raise ОшибкаПроверки(
                f"таблица '{имя}': строк со значением '{значение}' в колонке "
                f"'{колонка}' — {количество}, ожидалось {ожидаемое}"
            )
    return (
        f"таблица '{имя}': строк со значением '{значение}' "
        f"в колонке '{колонка}' — {количество}"
    )


