def _проверить_имя(имя: str) -> str:
    if not isinstance(имя, str):
        raise ОшибкаАгентскогоAPI("имя теста должно быть строкой")
    имя = имя.strip()
    if (
        not имя
        or Path(имя).name != имя
        or имя in {".", ".."}
        or имя.startswith((".", "_"))
    ):
        raise ОшибкаАгентскогоAPI(
            "ожидается имя каталога теста без пути, например 'главная-смоук'"
        )
    return имя


def разрешить_тест(каталог_тестов: Path, имя: str) -> Path:
    """Безопасно разрешить простое имя существующего теста внутри tests/."""
    имя = _проверить_имя(имя)

    корень = каталог_тестов.resolve()
    кандидат = (корень / имя).resolve()
    if кандидат.parent != корень:
        raise ОшибкаАгентскогоAPI("каталог теста должен находиться непосредственно в tests/")
    if not кандидат.is_dir() or not (кандидат / "init.json").is_file():
        raise ОшибкаАгентскогоAPI(f"тест '{имя}' не найден")
    if (кандидат / "init.json").is_symlink():
        raise ОшибкаАгентскогоAPI("init.json теста не может быть символической ссылкой")
    return кандидат


def проверить_тест(
    каталог_тестов: Path,
    имя: str,
    политика: ПолитикаХостов | None = None,
) -> dict[str, Any]:
    """Статически проверить init.json, Gherkin и все фразы существующего теста."""
    каталог = разрешить_тест(каталог_тестов, имя)
    try:
        настройки = Настройки.прочитать(каталог)
        тест = Тест.прочитать(настройки)
        _проверить_адреса_теста(тест, политика)
    except ОшибкаЗагрузки as ошибка:
        raise ОшибкаАгентскогоAPI(str(ошибка)) from ошибка
    except ОшибкаПолитикиХостов as ошибка:
        raise ОшибкаАгентскогоAPI(str(ошибка)) from ошибка

    return {
        "валиден": True,
        "тест": имя,
        **_описать_тест(тест),
    }


def проверить_черновик(
    имя: str,
    init_json: str,
    feature: str,
    политика: ПолитикаХостов | None = None,
) -> dict[str, Any]:
    """Проверить будущий тест полностью в памяти и вернуть диагностики."""
    имя = _проверить_имя(имя)
    if not isinstance(init_json, str) or not isinstance(feature, str):
        raise ОшибкаАгентскогоAPI("'init_json' и 'feature' должны быть строками")

    диагностики: list[dict[str, Any]] = []
    try:
        данные = json.loads(init_json)
    except json.JSONDecodeError as ошибка:
        диагностики.append(
            _диагностика(
                "init.json",
                "INIT_JSON",
                f"некорректный JSON: {ошибка.msg}",
                ошибка.lineno,
            )
        )
        return _результат_черновика(имя, диагностики)

    try:
        настройки = Настройки.из_словаря(данные, Path("tests") / имя)
    except (ОшибкаЗагрузки, TypeError, ValueError) as ошибка:
        диагностики.append(
            _диагностика("init.json", "INIT_SCHEMA", str(ошибка))
        )
        return _результат_черновика(имя, диагностики)

    if политика is not None and настройки.базовый_адрес:
        try:
            политика.проверить_url(настройки.базовый_адрес)
        except ОшибкаПолитикиХостов as ошибка:
            диагностики.append(
                _диагностика("init.json", "HOST_NOT_ALLOWED", str(ошибка))
            )

    использованные: dict[str, int] = {}
    for номер, строка in enumerate(feature.splitlines(), start=1):
        for параметр in _ПАРАМЕТР.findall(строка):
            использованные.setdefault(параметр, номер)
    for параметр, строка in использованные.items():
        if параметр not in настройки.параметры:
            диагностики.append(
                _диагностика(
                    "test.feature",
                    "MISSING_PARAMETER",
                    f"параметр '${{{параметр}}}' отсутствует в init.json",
                    строка,
                )
            )

    пробелы_языка = []
    for номер, строка in enumerate(feature.splitlines(), start=1):
        совпадение = _ТЗ.match(строка)
        if not совпадение:
            continue
        текст_тз = совпадение.group(1)
        ссылка_gap = _ССЫЛКА_GAP.match(текст_тз)
        пробелы_языка.append(
            {
                "строка": номер,
                "тз": текст_тз,
                "engine_gap": ссылка_gap.group(1) if ссылка_gap else None,
            }
        )

    тест: Тест | None = None
    try:
        тест = Тест.из_текста(настройки, feature, "test.feature")
    except ОшибкаЗагрузки as ошибка:
        диагностики.append(_диагностика_загрузки(str(ошибка)))
    if тест is not None and политика is not None:
        for номер, строка in enumerate(feature.splitlines(), start=1):
            if строка.lstrip().startswith("#"):
                continue
            for адрес in re.findall(r'https?://[^"\s]+', строка):
                try:
                    политика.проверить_url(адрес)
                except ОшибкаПолитикиХостов as ошибка:
                    диагностики.append(
                        _диагностика(
                            "test.feature",
                            "HOST_NOT_ALLOWED",
                            str(ошибка),
                            номер,
                        )
                    )

    результат = _результат_черновика(имя, диагностики, пробелы_языка)
    if тест is not None:
        результат.update(_описать_тест(тест))
    return результат


def _описать_тест(тест: Тест) -> dict[str, Any]:
    return {
        "функция": тест.имя,
        "сценарии": [
            {
                "имя": сценарий.имя,
                "пропустить": сценарий.пропустить,
                "шаги": [
                    {
                        "номер": шаг.номер,
                        "фраза": шаг.имя,
                        "действие": шаг.действие,
                        "аргументы": шаг.аргументы,
                    }
                    for шаг in сценарий.шаги
                ],
            }
            for сценарий in тест.сценарии
        ],
    }


def _результат_черновика(
    имя: str,
    диагностики: list[dict[str, Any]],
    пробелы_языка: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    пробелы_языка = пробелы_языка or []
    исполняем = not any(
        диагностика["уровень"] == "ошибка" for диагностика in диагностики
    )
    if not исполняем:
        состояние = СОСТОЯНИЕ_НЕВАЛИДЕН
    elif пробелы_языка:
        состояние = СОСТОЯНИЕ_ДЫРА_ЯЗЫКА
    else:
        состояние = СОСТОЯНИЕ_ЧЕРНОВИК
    return {
        "тест": имя,
        "исполняем": исполняем,
        "полон": исполняем and not пробелы_языка,
        "состояние": состояние,
        "диагностики": диагностики,
        "пробелы_языка": пробелы_языка,
    }


def _диагностика(
    файл: str,
    категория: str,
    сообщение: str,
    строка: int | None = None,
) -> dict[str, Any]:
    return {
        "уровень": "ошибка",
        "категория": категория,
        "файл": файл,
        "строка": строка,
        "сообщение": сообщение,
    }


def _диагностика_загрузки(сообщение: str) -> dict[str, Any]:
    строка = None
    совпадение = re.search(r"test\.feature:(\d+):", сообщение)
    if совпадение:
        строка = int(совпадение.group(1))
    else:
        совпадение = re.search(r"\((\d+):\d+\)", сообщение)
        if совпадение:
            строка = int(совпадение.group(1))

    категория = "GHERKIN"
    if "шаг не распознан" in сообщение:
        категория = "UNKNOWN_STEP"
    return _диагностика("test.feature", категория, сообщение, строка)


def _проверить_адреса_теста(
    тест: Тест,
    политика: ПолитикаХостов | None,
) -> None:
    if политика is None:
        return
    if тест.настройки.базовый_адрес:
        политика.проверить_url(тест.настройки.базовый_адрес)
    for сценарий in тест.сценарии:
        for шаг in сценарий.шаги:
            for значение in шаг.аргументы.values():
                if isinstance(значение, str) and значение.startswith(
                    ("http://", "https://")
                ):
                    политика.проверить_url(значение)
